import type { HTMLAttributes } from "react";
import { useCallback, useEffect, useId, useState } from "react";

import { cn } from "./lib/cn";

export type MsgfSentinelTenantConfig = {
  /** Display name in the FAB dialog (e.g. "Author", "QA-Repo-A"). */
  productLabel: string;
  accentButtonClass?: string;
  accentRingClass?: string;
  accentTextClass?: string;
  fabIconClass?: string;
  fabBorderHoverClass?: string;
};

export const DEFAULT_MSGF_SENTINEL_TENANT: MsgfSentinelTenantConfig = {
  productLabel: "MSGF",
  accentButtonClass: "bg-violet-600 hover:bg-violet-500",
  accentRingClass: "ring-violet-500/40 focus:border-violet-600 focus:ring-2",
  accentTextClass: "text-violet-300/90",
  fabIconClass: "text-violet-300 hover:text-violet-200",
  fabBorderHoverClass: "hover:border-violet-500/60",
};

export type DiagnosticSnapshotPayload = Record<string, unknown>;

export type MsgfSentinelReportSuccess = {
  userMessage: string;
  resumePrompt?: string;
  healedPillars?: Array<{ pillar: string; label: string }>;
  /** High-level-only copy; never includes model prompts or LOM templates. */
  reasoningSummary?: { headline: string; detail: string | null };
  escalatedToArbitrate?: boolean;
  logicDrift?: { band: string; escalated: boolean; score: number };
};

export type MsgfSentinelProps = Omit<HTMLAttributes<HTMLDivElement>, "children"> & {
  tenantConfig?: MsgfSentinelTenantConfig;
  reportEndpointUrl: string;
  collectDiagnosticSnapshot: () => Promise<DiagnosticSnapshotPayload>;
  getAuthHeaders?: () => HeadersInit | Promise<HeadersInit>;
  submitReport?: (operatorNote: string) => Promise<MsgfSentinelReportSuccess>;
  /** When true (default), opening the dialog prefetches a preview of the diagnostic bundle (your excerpt + keystrokes). */
  enableGlassBox?: boolean;
};

type Phase = "idle" | "snapshotting" | "sending" | "ok" | "err";

function BugIcon({ className }: { className?: string }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      fill="none"
      viewBox="0 0 24 24"
      strokeWidth={1.5}
      stroke="currentColor"
      className={className}
      aria-hidden
    >
      <ellipse cx="12" cy="12" rx="3.5" ry="4.5" />
      <path
        strokeLinecap="round"
        d="M12 7V4M12 20v-3M7 10H4M20 10h-3M8 15l-2 2M16 15l2 2M8 9L6 7M16 9l2-2"
      />
    </svg>
  );
}

export function MsgfSentinel({
  tenantConfig,
  reportEndpointUrl,
  collectDiagnosticSnapshot,
  getAuthHeaders,
  submitReport,
  enableGlassBox = true,
  className,
  ...rest
}: MsgfSentinelProps) {
  const theme = { ...DEFAULT_MSGF_SENTINEL_TENANT, ...tenantConfig };
  const [open, setOpen] = useState(false);
  const [message, setMessage] = useState("");
  const [phase, setPhase] = useState<Phase>("idle");
  const [errText, setErrText] = useState("");
  const [successMessage, setSuccessMessage] = useState("");
  const [glassPreview, setGlassPreview] = useState<DiagnosticSnapshotPayload | null>(null);
  const [glassLoading, setGlassLoading] = useState(false);
  const [glassOpen, setGlassOpen] = useState(false);
  const [reasoningSummary, setReasoningSummary] = useState<{
    headline: string;
    detail: string | null;
  } | null>(null);
  const [logicDriftBrief, setLogicDriftBrief] = useState<string | null>(null);
  const baseId = useId();
  const msgId = `${baseId}-msg`;

  useEffect(() => {
    if (!open || !enableGlassBox) {
      setGlassPreview(null);
      setGlassLoading(false);
      return;
    }
    let cancelled = false;
    setGlassLoading(true);
    void (async () => {
      try {
        const snap = await collectDiagnosticSnapshot();
        if (!cancelled) setGlassPreview(snap);
      } catch {
        if (!cancelled) setGlassPreview(null);
      } finally {
        if (!cancelled) setGlassLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [open, enableGlassBox, collectDiagnosticSnapshot]);

  useEffect(() => {
    if (!open) {
      setReasoningSummary(null);
      setLogicDriftBrief(null);
    }
  }, [open]);

  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape" && phase !== "snapshotting" && phase !== "sending") {
        setOpen(false);
      }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, phase]);

  const submit = useCallback(async () => {
    const trimmed = message.trim();
    if (!trimmed || !reportEndpointUrl) return;

    setPhase("snapshotting");
    setErrText("");

    try {
      let userMessage: string;
      let dismissMs = 2800;
      let nextReasoning: { headline: string; detail: string | null } | null = null;
      let nextDrift: string | null = null;
      let nextGlass = false;

      if (submitReport) {
        const result = await submitReport(trimmed);
        userMessage = result.userMessage;
        nextReasoning = result.reasoningSummary ?? null;
        if (result.logicDrift?.band) {
          nextDrift = `Session drift: ${result.logicDrift.band}${
            result.logicDrift.escalated ? " · safeguard triggered" : ""
          }`;
        }
        nextGlass = result.escalatedToArbitrate === true;
      } else {
        const snapshot = await collectDiagnosticSnapshot();
        const payload = { ...snapshot, operator_note: trimmed };

        setPhase("sending");

        const extraHeaders = getAuthHeaders ? await getAuthHeaders() : {};
        const res = await fetch(reportEndpointUrl, {
          method: "POST",
          headers: { "Content-Type": "application/json", ...extraHeaders },
          credentials: "include",
          body: JSON.stringify(payload),
        });

        const data = (await res.json().catch(() => ({}))) as {
          ok?: boolean;
          error?: string;
          user_resume_message?: string;
          reasoning_summary?: { headline?: string; detail?: string | null };
          logic_drift?: { band?: string; escalated?: boolean; score?: number };
          escalated_to_arbitrate?: boolean;
        };

        if (!res.ok || data.ok === false) {
          setPhase("err");
          setErrText(
            typeof data.error === "string"
              ? data.error
              : `Request failed (${res.status})`
          );
          return;
        }

        userMessage =
          typeof data.user_resume_message === "string" && data.user_resume_message.trim()
            ? data.user_resume_message.trim()
            : "Diagnostic snapshot received. Ops may follow up in ARBITRATE if needed.";

        const head = typeof data.reasoning_summary?.headline === "string" ? data.reasoning_summary.headline.trim() : "";
        if (head) {
          nextReasoning = {
            headline: head,
            detail:
              typeof data.reasoning_summary?.detail === "string" && data.reasoning_summary.detail.trim()
                ? data.reasoning_summary.detail.trim()
                : null,
          };
        }
        if (data.logic_drift?.band) {
          nextDrift = `Session drift: ${data.logic_drift.band}${
            data.logic_drift.escalated ? " · safeguard triggered" : ""
          }`;
        }
        nextGlass = data.escalated_to_arbitrate === true;
      }

      if (nextReasoning || nextDrift || nextGlass) dismissMs = 12_000;

      setReasoningSummary(nextReasoning);
      setLogicDriftBrief(nextDrift);
      setGlassOpen(nextGlass);
      setSuccessMessage(userMessage);
      setPhase("ok");
      setMessage("");
      setTimeout(() => {
        setOpen(false);
        setPhase("idle");
        setSuccessMessage("");
        setReasoningSummary(null);
        setLogicDriftBrief(null);
        setGlassOpen(false);
      }, dismissMs);
    } catch (e) {
      setPhase("err");
      setErrText(e instanceof Error ? e.message : "Snapshot or report failed.");
    }
  }, [message, reportEndpointUrl, collectDiagnosticSnapshot, getAuthHeaders, submitReport]);

  const busy = phase === "snapshotting" || phase === "sending";
  const submitLabel =
    phase === "snapshotting"
      ? "Snapshotting…"
      : phase === "sending"
        ? "Sending…"
        : "Submit report";

  return (
    <div
      className={cn(
        "pointer-events-none fixed bottom-4 right-4 z-[100] flex flex-col items-end gap-2",
        className
      )}
      {...rest}
    >
      {open && (
        <div
          className="pointer-events-auto w-[min(28rem,calc(100vw-2rem))] max-h-[min(90vh,calc(100vh-2rem))] overflow-y-auto rounded-xl border border-zinc-700 bg-zinc-950 p-4 text-zinc-100 shadow-xl"
          role="dialog"
          aria-labelledby={`${baseId}-title`}
        >
          <h2 id={`${baseId}-title`} className="text-sm font-semibold tracking-tight">
            Report issue — {theme.productLabel}
          </h2>
          <p className="mt-1 text-xs text-zinc-500">
            The Brain will gather a full diagnostic snapshot (editor state, last 10 keystrokes,
            pillar health) before sending.
          </p>
          {busy ? (
            <p className={cn("mt-2 text-xs", theme.accentTextClass)} role="status">
              {phase === "snapshotting"
                ? "Snapshotting… collecting evidence from your session."
                : "Uploading diagnostic bundle to MSGF…"}
            </p>
          ) : null}
          {enableGlassBox ? (
            <details
              open={glassOpen}
              onToggle={(e) => setGlassOpen((e.target as HTMLDetailsElement).open)}
              className="mt-3 rounded-lg border border-zinc-800 bg-zinc-900/50"
            >
              <summary className="cursor-pointer select-none px-2 py-2 text-[11px] font-medium text-zinc-300">
                Diagnostic snapshot (your code &amp; keystrokes)
              </summary>
              <div className="space-y-2 border-t border-zinc-800/80 px-2 py-2 text-[10px] text-zinc-400">
                {glassLoading ? (
                  <p className={cn(theme.accentTextClass)}>Loading preview…</p>
                ) : glassPreview ? (
                  <>
                    <p>
                      <span className="text-zinc-500">Manuscript: </span>
                      <span className="text-zinc-200">
                        {String(
                          (glassPreview.editor as Record<string, unknown> | undefined)?.manuscript_title ??
                            "—"
                        )}
                      </span>
                    </p>
                    <div>
                      <p className="font-semibold text-zinc-500">Editor excerpt</p>
                      <pre className="mt-1 max-h-36 overflow-auto whitespace-pre-wrap break-words rounded bg-zinc-950 p-2 text-[10px] text-zinc-300">
                        {(() => {
                          const ex = (glassPreview.editor as Record<string, unknown> | undefined)
                            ?.editor_text_excerpt;
                          const text = typeof ex === "string" ? ex : "";
                          return (
                            text ||
                            "(No excerpt yet — use the HAL lab or any wired editor to capture text.)"
                          );
                        })()}
                      </pre>
                    </div>
                    <div>
                      <p className="font-semibold text-zinc-500">Recent keystrokes</p>
                      <ul className="mt-1 max-h-32 overflow-auto rounded bg-zinc-950 p-2 font-mono text-[9px] leading-snug text-zinc-400">
                        {(Array.isArray(glassPreview.keystrokes_last_10)
                          ? glassPreview.keystrokes_last_10
                          : []
                        ).map((row, i) => (
                          <li key={i} className="border-b border-zinc-800/80 py-0.5 last:border-0">
                            {typeof row === "object" && row !== null
                              ? JSON.stringify(row)
                              : String(row)}
                          </li>
                        ))}
                      </ul>
                    </div>
                  </>
                ) : (
                  <p>Preview unavailable.</p>
                )}
              </div>
            </details>
          ) : null}
          <label htmlFor={msgId} className="mt-3 block text-xs font-medium text-zinc-400">
            What went wrong?
          </label>
          <textarea
            id={msgId}
            value={message}
            onChange={(e) => setMessage(e.target.value)}
            rows={4}
            disabled={busy}
            className={cn(
              "mt-1 w-full resize-y rounded-lg border border-zinc-700 bg-zinc-900 px-3 py-2 text-sm text-zinc-100 outline-none placeholder:text-zinc-600 disabled:opacity-50",
              theme.accentRingClass
            )}
            placeholder="Steps to reproduce, error text, or what you expected…"
          />
          {phase === "err" && (
            <p className="mt-2 text-xs text-red-400" role="alert">
              {errText}
            </p>
          )}
          {phase === "ok" && (
            <div className="mt-2 space-y-2">
              <p className="text-xs text-emerald-400" role="status">
                {successMessage}
              </p>
              {(reasoningSummary || logicDriftBrief) && (
                <div className="rounded-lg border border-violet-900/45 bg-violet-950/25 p-2.5">
                  <p className="text-[10px] font-semibold uppercase tracking-wide text-violet-400/90">
                    Reasoning (high-level summary)
                  </p>
                  <p className="mt-1 text-[10px] text-zinc-500">
                    Internal model instructions and LOM prompt templates are never shown here.
                  </p>
                  {logicDriftBrief ? (
                    <p className="mt-2 text-[11px] text-violet-200/90">{logicDriftBrief}</p>
                  ) : null}
                  {reasoningSummary ? (
                    <>
                      <p className="mt-2 text-xs font-medium text-zinc-100">{reasoningSummary.headline}</p>
                      {reasoningSummary.detail ? (
                        <p className="mt-1 text-[11px] leading-relaxed text-zinc-400">
                          {reasoningSummary.detail}
                        </p>
                      ) : null}
                    </>
                  ) : null}
                </div>
              )}
            </div>
          )}
          <div className="mt-3 flex justify-end gap-2">
            <button
              type="button"
              disabled={busy}
              className="rounded-lg px-3 py-1.5 text-xs font-medium text-zinc-400 hover:bg-zinc-800 hover:text-zinc-200 disabled:opacity-40"
              onClick={() => {
                if (busy) return;
                setOpen(false);
                setPhase("idle");
                setErrText("");
                setGlassOpen(false);
              }}
            >
              Cancel
            </button>
            <button
              type="button"
              disabled={busy || !message.trim()}
              className={cn(
                "rounded-lg px-3 py-1.5 text-xs font-semibold text-white disabled:opacity-40",
                theme.accentButtonClass
              )}
              onClick={() => void submit()}
            >
              {submitLabel}
            </button>
          </div>
        </div>
      )}

      <button
        type="button"
        aria-expanded={open}
        aria-label={open ? "Close report issue" : `Report issue (${theme.productLabel})`}
        disabled={busy}
        className={cn(
          "pointer-events-auto flex h-12 w-12 items-center justify-center rounded-full border border-zinc-600 bg-zinc-900 shadow-lg transition hover:bg-zinc-800 disabled:opacity-60",
          theme.fabIconClass,
          theme.fabBorderHoverClass
        )}
        onClick={() => {
          if (busy) return;
          if (open) {
            setOpen(false);
            setPhase("idle");
            setErrText("");
            setGlassOpen(false);
            return;
          }
          setGlassOpen(false);
          setOpen(true);
        }}
      >
        <BugIcon className="h-6 w-6" />
      </button>
    </div>
  );
}

