/**
 * MSGF solo-service deep-test probe (no Author BFF).
 *
 * Exercises: /health, POST /api/msgf/pulse (license), GET heal-queue, v32-heartbeat dry-run.
 *
 * Env:
 *   MSGF_APP_URL (default http://127.0.0.1:3000)
 *   MSGF_CONTRACT_LICENSE_KEY or MSGF_SOLO_* + mint via bootstrap:solo
 *   MSGF_SOLO_TENANT_ID, MSGF_SOLO_ENTITY_ID
 *   MSGF_OPS_CRON_SECRET (optional, heartbeat)
 *   MSGF_PULSE_COOKIE (optional — browser session path instead of license)
 */
import { randomUUID } from "node:crypto";

const BASE = (
  process.env.MSGF_APP_URL ||
  process.env.NEXT_PUBLIC_MSGF_APP_URL ||
  "http://127.0.0.1:3000"
).replace(/\/+$/, "");

const TENANT =
  process.env.MSGF_SOLO_TENANT_ID?.trim() ||
  process.env.MSGF_TENANT_ID?.trim() ||
  "integration_sandbox";

const ENTITY =
  process.env.MSGF_SOLO_ENTITY_ID?.trim() ||
  process.env.MSGF_ENTITY_ID?.trim() ||
  "";

const LICENSE =
  process.env.MSGF_CONTRACT_LICENSE_KEY?.trim() ||
  process.env.MSGF_AUTHOR_PULSE_LICENSE_KEY?.trim() ||
  "";

const COOKIE = process.env.MSGF_PULSE_COOKIE?.trim() || "";
const CRON_SECRET = process.env.MSGF_OPS_CRON_SECRET?.trim() || "";

function sampleKeystrokes() {
  let ts = Date.now();
  const keys = ["h", "e", "l", "l", "o", " ", "w", "o", "r", "l", "d"];
  return keys.map((key, i) => {
    ts += 40 + i * 3;
    return {
      ts,
      key,
      type: "keydown",
      flightMs: 40 + (i % 5) * 8,
      dwellMs: 70 + (i % 4) * 5,
      target: "solo-probe",
    };
  });
}

async function probe(label, url, init = {}) {
  try {
    const res = await fetch(url, init);
    const text = await res.text();
    let json = null;
    try {
      json = JSON.parse(text);
    } catch {
      json = text.slice(0, 400);
    }
    return { ok: res.ok, status: res.status, json };
  } catch (e) {
    return { ok: false, status: 0, json: { error: e instanceof Error ? e.message : String(e) } };
  }
}

function logResult(label, r) {
  const mark = r.ok ? "OK" : "FAIL";
  console.log(`[${mark}] ${label} — HTTP ${r.status}`);
  console.log(JSON.stringify(r.json, null, 2).slice(0, 1200));
  if (JSON.stringify(r.json).length > 1200) console.log("  … truncated");
}

async function main() {
  console.log(`[probe:solo] ${BASE} — tenant=${TENANT}`);
  const failures = [];

  const health = await probe("GET /health", `${BASE}/health`);
  logResult("GET /health", health);
  if (!health.ok) failures.push("health");

  const entityId = ENTITY || randomUUID();
  if (!ENTITY) {
    console.log(`[warn] MSGF_SOLO_ENTITY_ID unset — using ephemeral ${entityId}`);
  }

  const pulseHeaders = {
    "Content-Type": "application/json",
    Accept: "application/json",
  };

  if (COOKIE) {
    pulseHeaders.Cookie = COOKIE;
  } else if (LICENSE) {
    pulseHeaders.Authorization = `Bearer ${LICENSE}`;
    pulseHeaders["x-msgf-license-key"] = LICENSE;
    pulseHeaders["x-msgf-ide-pulse"] = "1";
    pulseHeaders["x-msgf-entity-id"] = entityId;
    pulseHeaders["x-msgf-tenant-id"] = TENANT;
    pulseHeaders["X-MSGF-Tenant-Key"] = TENANT;
  } else {
    console.error(
      "[probe:solo] Set MSGF_CONTRACT_LICENSE_KEY (npm run bootstrap:solo -w msgf) or MSGF_PULSE_COOKIE"
    );
    process.exit(1);
  }

  const pulse = await probe("POST /api/msgf/pulse", `${BASE}/api/msgf/pulse`, {
    method: "POST",
    headers: pulseHeaders,
    body: JSON.stringify({ keystrokes: sampleKeystrokes() }),
  });
  logResult("POST /api/msgf/pulse", pulse);
  if (!pulse.ok && pulse.status !== 202) failures.push("pulse");

  const healHeaders = COOKIE ? { Cookie: COOKIE } : {};
  if (LICENSE) {
    healHeaders.Authorization = `Bearer ${LICENSE}`;
    healHeaders["x-msgf-license-key"] = LICENSE;
    healHeaders["x-msgf-tenant-id"] = TENANT;
    healHeaders["x-msgf-entity-id"] = entityId;
  }
  const heal = await probe(
    "GET /api/msgf/heal-queue",
    `${BASE}/api/msgf/heal-queue?tenant_id=${encodeURIComponent(TENANT)}`,
    { headers: healHeaders }
  );
  logResult("GET /api/msgf/heal-queue", heal);
  if (!heal.ok) failures.push("heal-queue");

  if (CRON_SECRET) {
    const hb = await probe("POST /api/msgf/ops/v32-heartbeat", `${BASE}/api/msgf/ops/v32-heartbeat`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${CRON_SECRET}`,
      },
      body: JSON.stringify({ dry_run: true }),
    });
    logResult("POST /api/msgf/ops/v32-heartbeat (dry_run)", hb);
    if (!hb.ok) failures.push("v32-heartbeat");
  } else {
    console.log("[skip] v32-heartbeat — set MSGF_OPS_CRON_SECRET to probe cron");
  }

  console.log("\n[probe:solo] MsgfBridge (other projects):");
  console.log("  import { MsgfBridge } from 'msgf/connector/MsgfBridge';");
  console.log(`  baseUrl: ${BASE}, tenantId: ${TENANT}, licenseKey: msgf_live_…`);

  if (failures.length) {
    console.error("\n[probe:solo] FAILED:", failures.join(", "));
    process.exit(1);
  }
  console.log("\n[probe:solo] All solo probes passed.");
}

main();
