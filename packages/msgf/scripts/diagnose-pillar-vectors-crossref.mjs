import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";
import pg from "pg";
import { createClient } from "@supabase/supabase-js";

import { resolveDatabaseUrl } from "./lib/normalize-database-url.mjs";

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
for (const rel of ["../../.env", "../../.env.local", ".env", ".env.local"]) {
  const p = path.resolve(pkgRoot, rel);
  if (fs.existsSync(p)) dotenv.config({ path: p, override: true });
}

const supabaseUrl =
  process.env.NEXT_PUBLIC_SUPABASE_URL?.trim() || process.env.SUPABASE_URL?.trim();
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY?.trim();
const { url: dbUrl } = resolveDatabaseUrl(process.env);

console.log("Supabase API:", supabaseUrl ? new URL(supabaseUrl).hostname : "(missing)");
console.log("Postgres:", dbUrl ? new URL(dbUrl).hostname : "(missing)");

if (dbUrl) {
  const client = new pg.Client({ connectionString: dbUrl });
  await client.connect();
  const col = await client.query(
    `SELECT column_name FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'pillar_vectors'
       AND column_name IN ('constraint_ledger','governance_pillar','genealogical_root')
     ORDER BY column_name`
  );
  console.log("Postgres pillar_vectors columns:", col.rows.map((r) => r.column_name).join(", ") || "(none)");
  await client.end();
}

if (supabaseUrl && serviceKey) {
  const sb = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const { error } = await sb.from("pillar_vectors").select("constraint_ledger").limit(1);
  console.log("PostgREST select constraint_ledger:", error ? `FAIL: ${error.message}` : "OK");
}
