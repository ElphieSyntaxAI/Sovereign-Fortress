/**
 * Bootstrap pillars + biometric baseline + pledge for IDE / shadow-scan readiness.
 *
 *   node scripts/init-tenant-brain.mjs --email=jessica@dealstar.io
 *   node scripts/init-tenant-brain.mjs --tenant=deckhostwmsgf/deck_host
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const msgfRoot = path.join(__dirname, "..");
const repoRoot = path.join(msgfRoot, "..", "..");
const require = createRequire(import.meta.url);

for (const p of [
  path.join(repoRoot, ".env"),
  path.join(repoRoot, ".env.local"),
  path.join(msgfRoot, ".env"),
  path.join(msgfRoot, ".env.local"),
]) {
  if (fs.existsSync(p)) require("dotenv").config({ path: p, override: true });
}

const { createClient } = await import("@supabase/supabase-js");

const CURRENT_LEGAL_VERSION =
  process.env.MSGF_LEGAL_VERSION?.trim() || "2026.05.05-UTAH-SAFE";

function parseArgs() {
  let email = "";
  let tenant = "";
  for (const arg of process.argv.slice(2)) {
    if (arg.startsWith("--email=")) email = arg.slice(8).trim().toLowerCase();
    else if (arg.startsWith("--tenant=")) tenant = arg.slice(9).trim();
  }
  return { email, tenant };
}

async function findUserIdByEmail(admin, email) {
  let page = 1;
  while (page <= 20) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw new Error(`listUsers: ${error.message}`);
    const hit = data.users.find((u) => u.email?.toLowerCase() === email);
    if (hit) return hit.id;
    if (data.users.length < 200) break;
    page += 1;
  }
  return null;
}

async function resolveTenants(admin, userId) {
  const tenants = new Set();
  const { data: ideRows } = await admin
    .from("msgf_ide_tokens")
    .select("tenant_id")
    .eq("user_id", userId)
    .is("revoked_at", null);
  for (const row of ideRows ?? []) {
    if (row.tenant_id?.trim()) tenants.add(row.tenant_id.trim());
  }
  const { data: profile } = await admin
    .from("p4_profiles")
    .select("tenant_id")
    .eq("user_id", userId)
    .maybeSingle();
  if (profile?.tenant_id?.trim()) tenants.add(profile.tenant_id.trim());
  const { data: projects } = await admin
    .from("msgf_user_projects")
    .select("project_origin")
    .eq("user_id", userId);
  for (const row of projects ?? []) {
    if (row.project_origin?.trim()) tenants.add(row.project_origin.trim());
  }
  return [...tenants];
}

async function ensureBiometricReady(admin, actorId) {
  const { error } = await admin.from("biometric_profile").upsert(
    {
      user_id: actorId,
      ewma_speed: 4.5,
      rhythm_hash: "r100-n10",
      baseline_training_remaining: 0,
      recalibrated_at: new Date().toISOString(),
    },
    { onConflict: "user_id" }
  );
  if (error) throw new Error(`biometric_profile: ${error.message}`);
}

async function ensurePledge(admin, entityId, tenantId) {
  const { data: existing } = await admin
    .from("state_beats")
    .select("id")
    .eq("author_id", entityId)
    .eq("legal_version", CURRENT_LEGAL_VERSION)
    .eq("label", "pledge")
    .limit(1)
    .maybeSingle();
  if (existing?.id) return;
  const { error } = await admin.from("state_beats").insert({
    author_id: entityId,
    tenant_id: tenantId,
    legal_version: CURRENT_LEGAL_VERSION,
    label: "pledge",
    beat_text: `No-AI-Training Pledge (admin init). Legal version: ${CURRENT_LEGAL_VERSION}.`,
  });
  if (error) throw new Error(`state_beats pledge: ${error.message}`);
}

async function ensurePillars(admin, tenantId) {
  const { bootstrapTenantBrain } = await import("../lib/services/brain-readiness.js");
  return bootstrapTenantBrain(admin, tenantId);
}

async function main() {
  const { email, tenant: tenantArg } = parseArgs();
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim() || process.env.SUPABASE_URL?.trim();
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY?.trim();
  if (!url || !key) {
    console.error("Missing Supabase URL / SUPABASE_SERVICE_ROLE_KEY");
    process.exit(1);
  }

  const admin = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  let userId = null;
  let tenantIds = tenantArg ? [tenantArg] : [];

  if (email) {
    userId = await findUserIdByEmail(admin, email);
    if (!userId) {
      console.error(`No user for ${email}`);
      process.exit(1);
    }
    console.log(`User: ${userId}`);
    if (!tenantIds.length) tenantIds = await resolveTenants(admin, userId);
  }

  if (!tenantIds.length) {
    console.error("No tenant — pass --tenant= or mint IDE token first.");
    process.exit(1);
  }

  for (const tenantId of tenantIds) {
    console.log(`\nTenant: ${tenantId}`);
    const boot = await ensurePillars(admin, tenantId);
    console.log(`  pillars: ${boot.pillars_present}/${boot.pillars_required}, created: ${boot.pillars_created?.length ?? 0}`);

    await ensureBiometricReady(admin, tenantId);
    console.log(`  biometric_profile: ready for tenant key actor`);

    if (userId) {
      await ensureBiometricReady(admin, userId);
      await ensurePledge(admin, userId, tenantId);
      console.log(`  biometric_profile + pledge: ready for user ${userId.slice(0, 8)}…`);
    }

    await ensurePledge(admin, tenantId, tenantId);
    console.log(`  pledge: ready for ingest actor (tenant id)`);

    const { computeBrainReadiness } = await import("../lib/services/brain-readiness.js");
    const asIngest = await computeBrainReadiness(admin, tenantId);
    const asUser = userId
      ? await computeBrainReadiness(admin, tenantId, userId)
      : null;
    console.log(`  readiness (ingest path): score=${asIngest.readiness_score} brain=${asIngest.brain_fully_initialized}`);
    if (asUser) {
      console.log(`  readiness (user entity): score=${asUser.readiness_score} brain=${asUser.brain_fully_initialized}`);
    }
  }

  console.log("\nDone. Re-run Shadow Scan in VS Code.");
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
