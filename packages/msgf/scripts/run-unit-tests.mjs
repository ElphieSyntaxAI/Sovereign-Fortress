/**
 * Cross-platform MSGF unit test runner (Windows, macOS, Linux).
 * Invokes tsx directly — avoids nested `npm run` spawn issues on Windows (EINVAL).
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** @type {{ label: string; args: string[] }[]} */
const UNIT_TESTS = [
  { label: "test:heal-queue", args: ["--test", "tests/heal-queue-schema.test.ts"] },
  { label: "test:ops-cron", args: ["--test", "tests/ops-cron-auth.test.ts"] },
  { label: "test:crossref-db", args: ["--test", "tests/crossref-db-enum-mirror.test.ts"] },
  { label: "test:remediation-circuit", args: ["--test", "tests/remediation-retry-circuit.test.ts"] },
  { label: "test:human-arbitration", args: ["--test", "tests/human-arbitration.test.ts"] },
  { label: "test:ingest-metadata", args: ["tests/ingest-metadata-validation.test.ts"] },
  { label: "test:token-usage-estimate", args: ["--test", "tests/token-usage-estimate.test.ts"] },
  { label: "test:heal-token-estimate", args: ["--test", "tests/heal-token-estimate.test.ts"] },
  { label: "test:credit-reservation", args: ["--test", "tests/credit-reservation-routing.test.ts"] },
  { label: "test:pulse-eco-savings", args: ["--test", "tests/pulse-eco-savings.test.ts"] },
  { label: "test:ingest-hash-cache", args: ["--test", "tests/ingest-hash-cache.test.ts"] },
  { label: "test:pulse-idempotency", args: ["--test", "tests/pulse-idempotency.test.ts"] },
  { label: "test:usage-monitor", args: ["--test", "tests/usage-monitor.test.ts"] },
  { label: "test:converge-context-budget", args: ["--test", "tests/converge-context-budget.test.ts"] },
  { label: "test:dev-session-profile", args: ["--test", "tests/dev-session-profile.test.ts"] },
  { label: "test:vault-active-file-shard", args: ["--test", "tests/vault-active-file-shard.test.ts"] },
  { label: "test:converge-cache", args: ["--test", "tests/converge-cache.test.ts"] },
  { label: "test:user-projects-bulk", args: ["--test", "tests/user-projects-bulk.test.ts"] },
  { label: "test:sentry-admin", args: ["--test", "tests/sentry-admin.test.ts"] },
  { label: "test:i1-a1-schema-helpers", args: ["--test", "tests/i1-a1-schema-helpers.test.ts"] },
];

function resolveTsxCli() {
  const candidates = [
    path.join(pkgRoot, "node_modules", "tsx", "dist", "cli.mjs"),
    path.join(pkgRoot, "..", "..", "node_modules", "tsx", "dist", "cli.mjs"),
  ];
  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

function runTsx(tsxCli, args) {
  const result = spawnSync(process.execPath, [tsxCli, ...args], {
    cwd: pkgRoot,
    stdio: "inherit",
    env: process.env,
  });
  return result.status ?? (result.error ? 1 : 0);
}

function main() {
  const tsxCli = resolveTsxCli();
  if (!tsxCli) {
    console.error(
      "[run-unit-tests] tsx not found. Run `npm install` from the monorepo root."
    );
    process.exit(1);
  }

  console.log(`[run-unit-tests] MSGF unit suite — ${process.platform} — ${pkgRoot}`);
  const failed = [];

  for (const t of UNIT_TESTS) {
    console.log(`\n--- ${t.label} ---\n`);
    const code = runTsx(tsxCli, t.args);
    if (code !== 0) failed.push({ label: t.label, code });
  }

  if (failed.length) {
    console.error("\n[run-unit-tests] FAILED:");
    for (const f of failed) console.error(`  - ${f.label} (exit ${f.code})`);
    process.exit(1);
  }

  console.log("\n[run-unit-tests] All unit scripts passed.");
  process.exit(0);
}

main();
