/**
 * Emits public API .d.ts stubs for server SDK entries (avoids Supabase TS2589 in rollup).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const distRoot = join(fileURLToPath(new URL("..", import.meta.url)), "dist");

function write(relPath, contents) {
  const full = join(distRoot, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents.trimStart() + "\n", "utf8");
  console.log(`[generate-server-dts] ${relPath}`);
}

