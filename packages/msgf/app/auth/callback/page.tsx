import { useEffect, useState } from "react";

import { msgfPostLoginPath, resolveAuthRedirectUrl } from "@/lib/auth-post-login";
import { createClient } from "@/utils/supabase/client";

function safeNext(raw: string | null): string {
  const n = raw?.trim();
  if (n && n.startsWith("/") && !n.startsWith("//")) return n;
  return msgfPostLoginPath();
}

/**
 * Completes Supabase auth after email confirm, magic link, or PKCE redirect.
 * Server `route.ts` cannot read URL hash fragments; this page handles `code`,
 * `token_hash`, and implicit hash sessions in the browser.
 */
export default function AuthCallbackPage() {
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;

    async function complete() {
      const params = new URLSearchParams(window.location.search);
      const next = safeNext(params.get("next"));
      const isAdminDest = next.startsWith("/admin");

      try {
        const supabase = createClient();
        const code = params.get("code");
        const tokenHash = params.get("token_hash");
        const type = params.get("type");

        if (code) {
          const { error: exchangeErr } = await supabase.auth.exchangeCodeForSession(code);
          if (exchangeErr) throw exchangeErr;
        } else if (tokenHash && type) {
          const { error: otpErr } = await supabase.auth.verifyOtp({
            token_hash: tokenHash,
            type: type as "signup" | "invite" | "magiclink" | "recovery" | "email_change" | "email",
          });
          if (otpErr) throw otpErr;
        }

        const { data: sessionData, error: sessionErr } = await supabase.auth.getSession();
        if (sessionErr) throw sessionErr;

        if (!sessionData.session) {
          throw new Error(
            "No session after auth callback. Confirm the link was opened on the same host that sent the email, or sign in with password."
          );
        }

        // Persist GitHub provider_token when linking / signing in with GitHub (repo picker).
        const providerToken = sessionData.session.provider_token?.trim();
        const identities = sessionData.session.user?.identities ?? [];
        const hasGithubIdentity = identities.some((id) => id.provider === "github");
        if (providerToken && hasGithubIdentity) {
          try {
            await fetch("/api/msgf/github/connection", {
              method: "POST",
              credentials: "include",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                access_token: providerToken,
                scopes: "read:user repo",
              }),
            });
          } catch (persistErr) {
            console.warn("[auth/callback] GitHub token persist failed", persistErr);
          }
        }

        // Google Workspace SSO — domain allowlist → company attach (I3).
        const hasGoogleIdentity = identities.some((id) => id.provider === "google");
        if (hasGoogleIdentity) {
          try {
            const ssoRes = await fetch("/api/msgf/auth/workspace-sso-complete", {
              method: "POST",
              credentials: "include",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({ next }),
            });
            const ssoJson = (await ssoRes.json()) as {
              ok?: boolean;
              redirect?: string;
              message?: string;
            };
            if (!ssoRes.ok || !ssoJson.ok) {
              if (isAdminDest && (ssoRes.status === 401 || ssoJson.ok === false)) {
                const dest =
                  ssoJson.redirect && ssoJson.redirect.startsWith("/admin")
                    ? ssoJson.redirect
                    : next;
                if (ssoRes.status === 401) {
                  if (cancelled) return;
                  window.location.assign(resolveAuthRedirectUrl(dest));
                  return;
                }
              }
              await supabase.auth.signOut().catch(() => undefined);
              const dest =
                ssoJson.redirect ||
                `/invite-only?reason=domain_unmapped`;
              if (cancelled) return;
              window.location.assign(resolveAuthRedirectUrl(dest));
              return;
            }
            if (cancelled) return;
            window.location.assign(
              resolveAuthRedirectUrl(ssoJson.redirect || next)
            );
            return;
          } catch (ssoErr) {
            console.warn("[auth/callback] Workspace SSO complete failed", ssoErr);
            await fetch("/api/msgf/auth/google-sso-status", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({ event: "failure", reason: "callback_exception" }),
            }).catch(() => undefined);
          }
        }

        if (cancelled) return;
        window.location.assign(resolveAuthRedirectUrl(next));
      } catch (e) {
        if (cancelled) return;
        const msg = e instanceof Error ? e.message : String(e);
        console.error("[auth/callback]", e);
        setError(msg);
        const signIn = isAdminDest
          ? `/admin/sign-in?error=auth_callback&next=${encodeURIComponent(next)}`
          : "/sign-in?error=auth_callback";
        window.setTimeout(() => {
          window.location.assign(resolveAuthRedirectUrl(signIn));
        }, 4000);
      }
    }

    void complete();
    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <main className="landing-mesh flex min-h-screen items-center justify-center px-6 text-slate-200">
      <div className="glass-panel max-w-md rounded-2xl p-8 text-center">
        <p className="text-sm text-slate-300">
          {error ? "Sign-in could not be completed." : "Finishing sign-in…"}
        </p>
        {error ? (
          <p className="mt-3 text-xs text-red-300/90">{error}</p>
        ) : (
          <p className="mt-2 text-xs text-slate-500">Redirecting to your dashboard.</p>
        )}
      </div>
    </main>
  );
}
