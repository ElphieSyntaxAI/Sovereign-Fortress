import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

type Props = {
  projectOrigin: string;
};

export function ProjectIdeTokenControls({ projectOrigin }: Props) {
  const [loading, setLoading] = useState(true);
  const [hasActive, setHasActive] = useState(false);
  const [expiresAt, setExpiresAt] = useState<string | null>(null);
  const [minting, setMinting] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);

  const refreshStatus = useCallback(async () => {
    setLoading(true);
    try {
      const res = await fetch(
        `/api/workspace/ide-tokens?project_origin=${encodeURIComponent(projectOrigin)}`,
        { credentials: "include" }
      );
      const data = (await res.json().catch(() => ({}))) as {
        has_active_token?: boolean;
        tokens?: Array<{ expires_at: string }>;
      };
      setHasActive(Boolean(data.has_active_token));
      setExpiresAt(data.tokens?.[0]?.expires_at ?? null);
    } catch {
      setHasActive(false);
      setExpiresAt(null);
    } finally {
      setLoading(false);
    }
  }, [projectOrigin]);

  useEffect(() => {
    void refreshStatus();
  }, [refreshStatus]);

  const mintToken = useCallback(async () => {
    setMinting(true);
    setNotice(null);
    try {
      const res = await fetch("/api/workspace/ide-tokens", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ project_origin: projectOrigin }),
      });
      const data = (await res.json().catch(() => ({}))) as {
        ok?: boolean;
        error?: string;
        settingsJson?: string;
        warning?: string;
      };
      if (!res.ok || data.ok === false) {
        throw new Error(data.error ?? "Could not mint IDE token.");
      }
      if (data.settingsJson) {
        await navigator.clipboard.writeText(data.settingsJson);
      }
      setNotice(
        data.warning ??
          "Long-lived token minted — settings copied. Paste into .vscode/settings.json and reload the window."
      );
      await refreshStatus();
    } catch (e) {
      setNotice(e instanceof Error ? e.message : "Mint failed.");
    } finally {
      setMinting(false);
    }
  }, [projectOrigin, refreshStatus]);

  const workspaceHref = `/workspace?tab=ide&project_origin=${encodeURIComponent(projectOrigin)}`;

  return (
    <div className="flex flex-col items-end gap-1.5 text-right">
      {loading ? (
        <span className="text-xs text-slate-500">Checking IDE token…</span>
      ) : hasActive && expiresAt ? (
        <span className="text-xs text-emerald-400">
          IDE token active · expires {new Date(expiresAt).toLocaleDateString()}
        </span>
      ) : (
        <span className="text-xs text-amber-300/90">No active IDE token</span>
      )}
      <div className="flex flex-wrap justify-end gap-2">
        <Link
          href={workspaceHref}
          className="rounded-full border border-cyan-500/30 bg-cyan-500/10 px-3 py-1.5 text-xs font-medium text-cyan-100 hover:bg-cyan-500/20"
        >
          IDE setup
        </Link>
        <button
          type="button"
          disabled={minting}
          onClick={() => void mintToken()}
          className="rounded-full border border-violet-500/40 bg-violet-500/15 px-3 py-1.5 text-xs font-medium text-violet-100 hover:bg-violet-500/25 disabled:opacity-50"
        >
          {minting ? "Minting…" : hasActive ? "Mint new token" : "Mint IDE token"}
        </button>
      </div>
      {notice ? (
        <p className="max-w-xs text-xs text-emerald-300" role="status">
          {notice}
        </p>
      ) : null}
    </div>
  );
}
