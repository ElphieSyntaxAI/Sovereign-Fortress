import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

import type { UserProjectRow } from "@/lib/services/user-projects";

export function ProjectSetupClient() {
  const [projects, setProjects] = useState<UserProjectRow[]>([]);
  const [sourceType, setSourceType] = useState<"local" | "github">("local");
  const [displayName, setDisplayName] = useState("");
  const [localPath, setLocalPath] = useState("");
  const [githubUrl, setGithubUrl] = useState("");
  const [projectOrigin, setProjectOrigin] = useState("");
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [monorepoPresets, setMonorepoPresets] = useState<
    Array<{
      id: string;
      display_name: string;
      project_origin: string;
      suggested_local_path: string;
    }>
  >([]);
  const [addingPresetId, setAddingPresetId] = useState<string | null>(null);

  const loadProjects = useCallback(async () => {
    setLoading(true);
    try {
      const res = await fetch("/api/msgf/projects", { credentials: "include", cache: "no-store" });
      const json = (await res.json()) as { ok: boolean; projects?: UserProjectRow[]; error?: string };
      if (!res.ok || !json.ok) {
        throw new Error(json.error ?? `HTTP ${res.status}`);
      }
      setProjects(json.projects ?? []);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to load projects.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void loadProjects();
    fetch("/api/workspace/monorepo-presets", { credentials: "include", cache: "no-store" })
      .then(async (res) => {
        const json = (await res.json()) as {
          ok?: boolean;
          presets?: typeof monorepoPresets;
        };
        if (json.ok && json.presets) setMonorepoPresets(json.presets);
      })
      .catch(() => setMonorepoPresets([]));
  }, [loadProjects]);

  async function addMonorepoPreset(presetId: string) {
    const preset = monorepoPresets.find((p) => p.id === presetId);
    if (!preset) return;
    setAddingPresetId(presetId);
    setError(null);
    try {
      const res = await fetch("/api/msgf/projects", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          source_type: "local",
          display_name: preset.display_name,
          local_path: preset.suggested_local_path,
          project_origin: preset.project_origin,
        }),
      });
      const json = (await res.json()) as { ok: boolean; error?: string };
      if (!res.ok || !json.ok) throw new Error(json.error ?? `HTTP ${res.status}`);
      setMessage(`Mapped workspace: ${preset.display_name}`);
      await loadProjects();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to add preset workspace.");
    } finally {
      setAddingPresetId(null);
    }
  }

  async function handleSubmit(event: React.FormEvent) {
    event.preventDefault();
    setSaving(true);
    setMessage(null);
    setError(null);
    try {
      const body =
        sourceType === "local"
          ? {
              source_type: "local" as const,
              display_name: displayName.trim(),
              local_path: localPath.trim(),
              ...(projectOrigin.trim() ? { project_origin: projectOrigin.trim() } : {}),
            }
          : {
              source_type: "github" as const,
              display_name: displayName.trim(),
              github_url: githubUrl.trim(),
              ...(projectOrigin.trim() ? { project_origin: projectOrigin.trim() } : {}),
            };

      const res = await fetch("/api/msgf/projects", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      const json = (await res.json()) as { ok: boolean; error?: string };
      if (!res.ok || !json.ok) {
        throw new Error(json.error ?? `HTTP ${res.status}`);
      }
      setDisplayName("");
      setLocalPath("");
      setGithubUrl("");
      setProjectOrigin("");
      setMessage("Project mapped. Eco metrics and pillar health will scope to this origin tag.");
      await loadProjects();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to save project.");
    } finally {
      setSaving(false);
    }
  }

  async function handleDelete(id: string) {
    setError(null);
    const res = await fetch(`/api/msgf/projects/${id}`, {
      method: "DELETE",
      credentials: "include",
    });
    const json = (await res.json()) as { ok: boolean; error?: string };
    if (!res.ok || !json.ok) {
      setError(json.error ?? "Failed to delete project.");
      return;
    }
    await loadProjects();
  }

  return (
    <div className="space-y-8">
      <section className="glass-panel rounded-2xl border border-cyan-500/20 p-6">
        <h2 className="text-lg font-semibold text-slate-100">How mapping works</h2>
        <ul className="mt-4 space-y-2 text-sm text-slate-300">
          <li>
            <strong className="text-cyan-200">Monorepo rule</strong> — add{" "}
            <strong>one workspace per app</strong> (e.g. <code className="text-cyan-100">apps/author-ecosystem</code>
            , <code className="text-cyan-100">packages/msgf</code>), not only the git root. Each row is an
            independent <code className="text-cyan-100">project_origin</code> for Small Brain scoping.
          </li>
          <li>
            <strong className="text-cyan-200">Local projects</strong> — register the folder path where
            Pulse Guard runs. MSGF derives a stable <code className="text-cyan-100">project_origin</code>{" "}
            tag from that path when you do not override it.
          </li>
          <li>
            <strong className="text-cyan-200">GitHub repositories</strong> — paste a{" "}
            <code className="text-cyan-100">github.com/owner/repo</code> URL. We map telemetry to that
            repository identity.
          </li>
          <li>
            Your dashboard pillar health and environmental usage aggregate only across mapped origins —
            not the entire Elphie Syntax network.
          </li>
          <li>
            Public landing pages still show global network totals until you sign in.
          </li>
        </ul>
      </section>

      {monorepoPresets.length > 0 ? (
        <section className="glass-panel rounded-2xl border border-violet-500/20 p-6">
          <h2 className="text-lg font-semibold text-slate-100">Elphie Syntax monorepo apps</h2>
          <p className="mt-2 text-sm text-slate-400">
            One-click workspace rows — each product app is its own project (recommended for this repo).
          </p>
          <ul className="mt-4 space-y-2">
            {monorepoPresets.map((preset) => {
              const mapped = projects.some((p) => p.project_origin === preset.project_origin);
              return (
                <li
                  key={preset.id}
                  className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-slate-800 px-4 py-3 text-sm"
                >
                  <div>
                    <p className="font-medium text-slate-100">{preset.display_name}</p>
                    <p className="font-mono text-xs text-slate-500">{preset.project_origin}</p>
                    <p className="text-xs text-slate-600">{preset.suggested_local_path}</p>
                  </div>
                  {mapped ? (
                    <span className="text-xs text-emerald-400">Mapped</span>
                  ) : (
                    <button
                      type="button"
                      disabled={addingPresetId === preset.id}
                      onClick={() => void addMonorepoPreset(preset.id)}
                      className="rounded-full border border-violet-500/40 bg-violet-500/15 px-3 py-1.5 text-xs font-medium text-violet-100 hover:bg-violet-500/25 disabled:opacity-50"
                    >
                      {addingPresetId === preset.id ? "Adding…" : "Add workspace"}
                    </button>
                  )}
                </li>
              );
            })}
          </ul>
        </section>
      ) : null}

      <form
        onSubmit={(e) => void handleSubmit(e)}
        className="glass-panel space-y-4 rounded-2xl border border-emerald-500/20 p-6"
      >
        <h2 className="text-lg font-semibold text-slate-100">Add a custom project</h2>

        <div className="flex flex-wrap gap-2">
          {(["local", "github"] as const).map((type) => (
            <button
              key={type}
              type="button"
              onClick={() => setSourceType(type)}
              className={`rounded-full border px-4 py-2 text-sm font-medium transition ${
                sourceType === type
                  ? "border-emerald-500/40 bg-emerald-500/20 text-emerald-100"
                  : "border-slate-700 text-slate-400 hover:border-slate-500"
              }`}
            >
              {type === "local" ? "Local folder" : "GitHub repo"}
            </button>
          ))}
        </div>

        <label className="block text-sm text-slate-300">
          Display name
          <input
            required
            value={displayName}
            onChange={(e) => setDisplayName(e.target.value)}
            className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-slate-100"
            placeholder="My SaaS monorepo"
          />
        </label>

        {sourceType === "local" ? (
          <label className="block text-sm text-slate-300">
            Local path
            <input
              required
              value={localPath}
              onChange={(e) => setLocalPath(e.target.value)}
              className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
              placeholder="C:/dev/my-app or /home/you/projects/my-app"
            />
          </label>
        ) : (
          <label className="block text-sm text-slate-300">
            GitHub URL
            <input
              required
              type="url"
              value={githubUrl}
              onChange={(e) => setGithubUrl(e.target.value)}
              className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
              placeholder="https://github.com/owner/repository"
            />
          </label>
        )}

        <label className="block text-sm text-slate-300">
          Optional project origin override
          <input
            value={projectOrigin}
            onChange={(e) => setProjectOrigin(e.target.value)}
            className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
            placeholder="owner/repo or custom/tag"
          />
        </label>

        {message ? (
          <p className="text-sm text-emerald-300" role="status">
            {message}
          </p>
        ) : null}
        {error ? (
          <p className="text-sm text-amber-200" role="alert">
            {error}
          </p>
        ) : null}

        <button
          type="submit"
          disabled={saving}
          className="rounded-full border border-emerald-500/40 bg-emerald-500/20 px-5 py-2 text-sm font-semibold text-emerald-100 transition hover:bg-emerald-500/30 disabled:opacity-50"
        >
          {saving ? "Saving…" : "Save project mapping"}
        </button>
      </form>

      <section className="glass-panel rounded-2xl border border-violet-500/15 p-6">
        <h2 className="text-lg font-semibold text-slate-100">Your mapped projects</h2>
        {loading ? <p className="mt-3 text-sm text-slate-500">Loading…</p> : null}
        {!loading && projects.length === 0 ? (
          <p className="mt-3 text-sm text-slate-400">No projects mapped yet.</p>
        ) : null}
        <ul className="mt-4 space-y-2">
          {projects.map((project) => (
            <li
              key={project.id}
              className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-slate-800 px-4 py-3 text-sm"
            >
              <div>
                <p className="font-medium text-slate-100">{project.display_name}</p>
                <p className="text-xs text-slate-500 font-mono">{project.project_origin}</p>
              </div>
              <button
                type="button"
                onClick={() => void handleDelete(project.id)}
                className="text-xs text-rose-300 underline-offset-4 hover:underline"
              >
                Remove
              </button>
            </li>
          ))}
        </ul>
        <p className="mt-6 text-sm text-slate-500">
          <Link href="/dashboard" className="text-emerald-300 underline-offset-4 hover:underline">
            ← Back to governance dashboard
          </Link>
        </p>
      </section>
    </div>
  );
}
