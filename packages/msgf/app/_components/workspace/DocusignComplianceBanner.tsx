import { useCallback, useEffect, useState } from "react";

import { usePostMvpGates } from "@/app/_components/feature-gates/usePostMvpGates";

type ComplianceResponse = {
  ok: boolean;
  account_status?: string;
  signing_url?: string | null;
  is_locked?: boolean;
  error?: string;
};

export function DocusignComplianceBanner() {
  const gates = usePostMvpGates();
  const [status, setStatus] = useState<ComplianceResponse | null>(null);
  const [completing, setCompleting] = useState(false);

  const load = useCallback(async () => {
    try {
      const res = await fetch("/api/msgf/workspace/compliance-status", {
        credentials: "include",
        cache: "no-store",
      });
      const json = (await res.json()) as ComplianceResponse;
      if (res.ok && json.ok) setStatus(json);
      else setStatus(null);
    } catch {
      setStatus(null);
    }
  }, []);

  useEffect(() => {
    if (!gates.signing) return;
    void load();
  }, [load, gates.signing]);

  if (!gates.signing) return null;
  if (!status?.is_locked && status?.account_status !== "pending_signatures") {
    return null;
  }

  const signingUrl = status.signing_url;
  const params =
    typeof window !== "undefined" ? new URLSearchParams(window.location.search) : null;
  const mockMode = params?.get("mock_docusign") === "1";
  const inviteId = params?.get("invite") ?? "";

  async function completeMock() {
    setCompleting(true);
    try {
      const res = await fetch("/api/msgf/workspace/docusign/mock-complete", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ invite_id: inviteId }),
      });
      const json = (await res.json()) as { ok?: boolean; error?: string };
      if (!res.ok || !json.ok) throw new Error(json.error ?? "Completion failed.");
      await load();
      if (typeof window !== "undefined") {
        const url = new URL(window.location.href);
        url.searchParams.delete("mock_docusign");
        window.history.replaceState(null, "", url.toString());
      }
    } catch (e) {
      alert(e instanceof Error ? e.message : "Could not complete mock DocuSign.");
    } finally {
      setCompleting(false);
    }
  }

  return (
    <section className="glass-panel rounded-2xl border border-amber-500/35 bg-amber-500/10 p-4 sm:p-5">
      <p className="text-sm font-semibold text-amber-100">DocuSign signature required</p>
      <p className="mt-2 text-sm text-slate-300">
        Your account is locked until the team compliance envelope is completed. Dev and security roles
        cannot use the IDE until signatures clear.
      </p>
      <div className="mt-4 flex flex-wrap gap-3">
        {signingUrl && !mockMode ? (
          <a
            href={signingUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="rounded-full bg-gradient-to-r from-amber-600 to-violet-600 px-5 py-2.5 text-sm font-semibold text-white shadow-lg"
          >
            Open DocuSign signing
          </a>
        ) : null}
        {mockMode ? (
          <button
            type="button"
            onClick={() => void completeMock()}
            disabled={completing}
            className="rounded-full border border-amber-400/40 bg-amber-500/20 px-5 py-2.5 text-sm font-semibold text-amber-50 disabled:opacity-60"
          >
            {completing ? "Activating…" : "Complete mock signature (dev)"}
          </button>
        ) : null}
      </div>
    </section>
  );
}
