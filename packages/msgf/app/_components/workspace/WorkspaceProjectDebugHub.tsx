import { useEffect, useState } from "react";

import { PULSE_GUARD_TRACKING } from "@/app/_components/workspace/workspace-ui";

type Props = {
  projectOrigin: string;
};

type PillarMini = { id: string; label: string; ok: boolean };

export function WorkspaceProjectDebugHub({ projectOrigin }: Props) {
  const [pillars, setPillars] = useState<PillarMini[]>([]);
  const [pillarsLoading, setPillarsLoading] = useState(true);
  const [issues, setIssues] = useState<
    Array<{ id: string; label: string; created_at: string }>
  >([]);

  useEffect(() => {
    let cancelled = false;
    void (async () => {
      setPillarsLoading(true);
      try {
        const healthRes = await fetch(
          `/api/msgf/health/pillars?project_origin=${encodeURIComponent(projectOrigin)}`,
          { credentials: "include" }
        );
        const health = (await healthRes.json()) as {
          ok?: boolean;
          pillars?: Record<string, { status?: string }>;
        };
        if (!cancelled && health.pillars) {
          setPillars(
            Object.entries(health.pillars).map(([id, p]) => ({
              id,
              label: id,
              ok: p.status === "healthy" || p.status === "ok",
            }))
          );
        } else if (!cancelled) {
          setPillars([]);
        }
      } catch {
        if (!cancelled) setPillars([]);
      } finally {
        if (!cancelled) setPillarsLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [projectOrigin]);

  return (
    <aside className="space-y-4">
      <div className="rounded-xl border border-slate-800 bg-slate-950/50 p-4">
        <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-400">
          Local pillar health
        </h4>
        <div className="mt-3 grid grid-cols-3 gap-2">
          {pillarsLoading ? (
            <div className="col-span-3 rounded-lg border border-slate-700/60 px-2 py-3 text-center text-[10px] text-slate-500">
              Loading pillar health…
            </div>
          ) : pillars.length === 0 ? (
            <div className="col-span-3 rounded-lg border border-amber-500/25 bg-amber-500/5 px-2 py-3 text-center text-[10px] text-amber-200/90">
              No pillar data yet — run Shadow Scan in the IDE, then refresh.
            </div>
          ) : (
            pillars.map((p) => (
              <div
                key={p.id}
                className={`rounded-lg border px-2 py-2 text-center text-[10px] font-medium ${
                  p.ok
                    ? "border-emerald-500/30 text-emerald-200"
                    : "border-rose-500/30 text-rose-200"
                }`}
              >
                {p.label}
              </div>
            ))
          )}
        </div>
      </div>

      <div className="rounded-xl border border-slate-800 bg-slate-950/50 p-4">
        <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-400">
          Hall &amp; Vault issues
        </h4>
        {issues.length === 0 ? (
          <p className="mt-2 text-xs text-slate-500">No local issues reported yet.</p>
        ) : (
          <ul className="mt-2 space-y-1 text-xs text-slate-400">
            {issues.map((i) => (
              <li key={i.id}>
                {i.label} · {new Date(i.created_at).toLocaleString()}
              </li>
            ))}
          </ul>
        )}
      </div>

      <div className="rounded-xl border border-slate-800 bg-slate-950/50 p-4">
        <h4 className="text-xs font-semibold uppercase tracking-wide text-slate-400">
          Local Pulse Guard rules
        </h4>
        <ul className="mt-2 space-y-1 text-xs text-slate-400">
          {PULSE_GUARD_TRACKING.extensions.map((ext) => (
            <li key={ext} className="font-mono text-cyan-200/80">
              {ext}
            </li>
          ))}
        </ul>
      </div>
    </aside>
  );
}
