import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

import { ConsensusPresetPanel } from "@/app/_components/dashboard/ConsensusPresetPanel";
import { PricingCtaButton } from "@/app/_components/pricing/PricingCtaButton";
import { GithubRepoPickerPanel } from "@/app/_components/workspace/GithubRepoPickerPanel";
import { LocalSubfolderPickerPanel } from "@/app/_components/workspace/LocalSubfolderPickerPanel";
import { InfoTip } from "@/app/_components/workspace/workspace-ui";
import { TeamManagementModule } from "@/app/_components/workspace/TeamManagementModule";
import { WorkspaceOnboardingPack } from "@/app/_components/workspace/WorkspaceOnboardingPack";
import type { SessionPermissions } from "@/lib/platform-rbac";
import { copyWorkspaceSetupPrompt } from "@/app/_components/workspace/copy-setup-prompt";
import type { UserProjectRow } from "@/lib/services/user-projects";

type MonorepoPreset = {
  id: string;
  display_name: string;
  project_origin: string;
  suggested_local_path: string;
};

type Props = {
  accessRole: string;
  companySilo: string;
  tenantKey: string;
  permissions?: SessionPermissions;
  onProjectsUpdated?: (projects: UserProjectRow[]) => void;
  surface?: "projects" | "access";
  highlightOrigin?: string | null;
};

export function WorkspaceSetupProjectsTab({
  accessRole,
  companySilo,
  tenantKey,
  permissions,
  onProjectsUpdated,
  surface = "projects",
  highlightOrigin,
}: Props) {
  const [projects, setProjects] = useState<UserProjectRow[]>([]);
  const [activity, setActivity] = useState<
    Record<
      string,
      { last_pulse_at: string | null; last_verify_at: string | null; sentry_quarantine_count: number }
    >
  >({});
  const [sourceType, setSourceType] = useState<"local" | "github">("local");
  const [displayName, setDisplayName] = useState("");
  const [localPath, setLocalPath] = useState("");
  const [githubUrl, setGithubUrl] = useState("");
  const [projectOrigin, setProjectOrigin] = useState("");
  const [loading, setLoading] = useState(true);
  const [promptCopied, setPromptCopied] = useState(false);
  const [saving, setSaving] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [monorepoPresets, setMonorepoPresets] = useState<MonorepoPreset[]>([]);
  const [addingPresetId, setAddingPresetId] = useState<string | null>(null);
  const [wizard, setWizard] = useState<null | "choose" | "github" | "local" | "preset">(null);
  const [presetAudience, setPresetAudience] = useState<"platform" | "customer" | null>(null);

  const loadProjects = useCallback(async () => {
    setLoading(true);
    try {
      const res = await fetch("/api/msgf/projects", { credentials: "include", cache: "no-store" });
      const json = (await res.json()) as {
        ok: boolean;
        projects?: UserProjectRow[];
        activity?: Record<
          string,
          {
            last_pulse_at: string | null;
            last_verify_at: string | null;
            sentry_quarantine_count: number;
          }
        >;
        error?: string;
      };
      if (!res.ok || !json.ok) {
        throw new Error(json.error ?? `HTTP ${res.status}`);
      }
      const list = json.projects ?? [];
      setProjects(list);
      setActivity(json.activity ?? {});
      onProjectsUpdated?.(list);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to load projects.");
    } finally {
      setLoading(false);
    }
  }, [onProjectsUpdated]);

  useEffect(() => {
    void loadProjects();
    fetch("/api/workspace/monorepo-presets", { credentials: "include", cache: "no-store" })
      .then(async (res) => {
        const json = (await res.json()) as {
          ok?: boolean;
          presets?: MonorepoPreset[];
          audience?: "platform" | "customer";
        };
        if (json.ok) {
          setMonorepoPresets(json.presets ?? []);
          setPresetAudience(json.audience ?? (json.presets?.length ? "platform" : "customer"));
        }
      })
      .catch(() => {
        setMonorepoPresets([]);
        setPresetAudience("customer");
      });
  }, [loadProjects]);

  async function addMonorepoPreset(presetId: string) {
    const preset = monorepoPresets.find((p) => p.id === presetId);
    if (!preset) return;
    setAddingPresetId(presetId);
    setError(null);
    try {
      const res = await fetch("/api/msgf/projects", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          source_type: "local",
          display_name: preset.display_name,
          local_path: preset.suggested_local_path,
          project_origin: preset.project_origin,
        }),
      });
      const json = (await res.json()) as { ok: boolean; error?: string };
      if (res.status === 409) throw new Error("Already mapped");
      if (!res.ok || !json.ok) throw new Error(typeof json.error === "string" ? json.error : `HTTP ${res.status}`);
      setMessage(`Mapped workspace: ${preset.display_name}`);
      await loadProjects();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to add preset workspace.");
    } finally {
      setAddingPresetId(null);
    }
  }

  async function handleSubmit(event: React.FormEvent) {
    event.preventDefault();
    setSaving(true);
    setMessage(null);
    setError(null);
    try {
      const body =
        sourceType === "local"
          ? {
              source_type: "local" as const,
              display_name: displayName.trim(),
              local_path: localPath.trim(),
              ...(projectOrigin.trim() ? { project_origin: projectOrigin.trim() } : {}),
            }
          : {
              source_type: "github" as const,
              display_name: displayName.trim(),
              github_url: githubUrl.trim(),
              ...(projectOrigin.trim() ? { project_origin: projectOrigin.trim() } : {}),
            };

      const res = await fetch("/api/msgf/projects", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      const json = (await res.json()) as { ok: boolean; error?: string };
      if (res.status === 409) throw new Error("Already mapped");
      if (!res.ok || !json.ok) {
        throw new Error(typeof json.error === "string" ? json.error : `HTTP ${res.status}`);
      }
      setDisplayName("");
      setLocalPath("");
      setGithubUrl("");
      setProjectOrigin("");
      setMessage("Project mapped. Mint its long-lived token in Active IDE below.");
      await loadProjects();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to save project.");
    } finally {
      setSaving(false);
    }
  }

  async function handleDelete(id: string) {
    setError(null);
    const res = await fetch(`/api/msgf/projects/${id}`, {
      method: "DELETE",
      credentials: "include",
    });
    const json = (await res.json()) as { ok: boolean; error?: string };
    if (!res.ok || !json.ok) {
      setError(json.error ?? "Failed to delete project.");
      return;
    }
    await loadProjects();
  }

  if (surface === "access") {
    return (
      <div className="space-y-4">
        {highlightOrigin ? (
          <p className="text-sm text-slate-400">
            Selected project origin{" "}
            <span className="font-mono text-emerald-200">{highlightOrigin}</span> stays highlighted in
            assignment. Access stays organization-wide.
          </p>
        ) : null}
        {permissions?.canManageTeam ? (
          <TeamManagementModule projects={projects} />
        ) : (
          <p className="text-sm text-slate-400">You do not manage team access for this workspace.</p>
        )}
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-2">
          <PricingCtaButton kind="extension_download" label="Download extension" variant="outline" />
          <button
            type="button"
            title="Paste into Cursor in your repo. One origin per app."
            onClick={() => {
              void copyWorkspaceSetupPrompt({
                tenantKey,
                existingOrigins: projects.map((project) => project.project_origin),
              }).then((text) => navigator.clipboard.writeText(text)).then(() => {
                setPromptCopied(true);
                window.setTimeout(() => setPromptCopied(false), 2000);
              });
            }}
            className="rounded-full border border-slate-600 px-4 py-2 text-sm text-slate-100"
          >
            {promptCopied ? "Copied" : "Copy setup prompt"}
          </button>
          <button
            type="button"
            onClick={() => setWizard("choose")}
            className="rounded-full bg-gradient-to-r from-emerald-600 to-violet-600 px-4 py-2 text-sm font-semibold text-white"
          >
            Add Project
          </button>
        </div>
        <details className="text-sm text-slate-400">
          <summary className="cursor-pointer text-slate-200">Developer / System Info</summary>
          <p className="mt-2">Access role: {accessRole}</p>
          <p className="mt-1">Sandbox status: {companySilo}</p>
          <p className="mt-1 break-all font-mono text-xs text-cyan-200">{tenantKey}</p>
          <button
            type="button"
            onClick={() => void navigator.clipboard.writeText(tenantKey)}
            className="mt-2 rounded border border-slate-600 px-2 py-1 text-xs text-slate-200"
          >
            Copy key
          </button>
        </details>
      </div>

      {wizard ? (
        <div className="fixed inset-0 z-50 overflow-y-auto bg-slate-950/80 p-4">
          <div className="mx-auto my-8 max-w-3xl space-y-4 rounded-2xl border border-slate-700 bg-slate-950 p-5">
            <div className="flex items-center justify-between">
              <h2 className="text-lg font-semibold text-slate-50">Add Project</h2>
              <button type="button" className="text-sm text-slate-300" onClick={() => setWizard(null)}>
                Close
              </button>
            </div>
            {wizard === "choose" ? (
              <div className="grid gap-3 sm:grid-cols-3">
                <button type="button" className="rounded-xl border border-slate-700 p-4 text-left" onClick={() => setWizard("github")}>
                  GitHub
                </button>
                <button type="button" className="rounded-xl border border-slate-700 p-4 text-left" onClick={() => setWizard("local")}>
                  Local folder
                </button>
                <button type="button" className="rounded-xl border border-slate-700 p-4 text-left" onClick={() => setWizard("preset")}>
                  Monorepo preset
                </button>
              </div>
            ) : (
              <button type="button" className="text-xs text-slate-400" onClick={() => setWizard("choose")}>
                Choose a different source
              </button>
            )}
            <div className={wizard === "github" ? "block" : "hidden"}>
      <GithubRepoPickerPanel
        projects={projects}
        onMapped={loadProjects}
        setError={setError}
        setMessage={setMessage}
      />
            </div>
            <div className={wizard === "local" ? "block" : "hidden"}>
      <LocalSubfolderPickerPanel
        projects={projects}
        onMapped={loadProjects}
        setError={setError}
        setMessage={setMessage}
      />
            </div>

      {(message || error) && (
        <div className="space-y-1">
          {message ? (
            <p className="text-sm text-emerald-300" role="status">
              {message}
            </p>
          ) : null}
          {error ? (
            <p className="text-sm text-amber-200" role="alert">
              {error}
            </p>
          ) : null}
        </div>
      )}

      <div className={wizard === "preset" ? "block space-y-4" : "hidden"}>
      <div className="flex flex-col gap-6 lg:grid lg:grid-cols-2 lg:items-start">
        <form
          onSubmit={(e) => void handleSubmit(e)}
          className="glass-panel min-w-0 space-y-4 rounded-2xl border border-emerald-500/20 p-5 sm:p-6"
        >
          <div>
            <h2 className="text-lg font-semibold text-slate-100">Connect repositories and subfolders</h2>
            <p className="mt-1 text-sm text-slate-400">
              Register repositories or monorepo subfolders as isolated project origins.
            </p>
          </div>

          <div className="flex flex-wrap gap-2">
            {(["local", "github"] as const).map((type) => (
              <button
                key={type}
                type="button"
                onClick={() => setSourceType(type)}
                className={`rounded-full border px-4 py-2 text-sm font-medium transition duration-200 ${
                  sourceType === type
                    ? "border-emerald-500/40 bg-emerald-500/20 text-emerald-100"
                    : "border-slate-700 text-slate-400 hover:border-slate-500"
                }`}
              >
                {type === "local" ? "Local Folder" : "GitHub Repo"}
              </button>
            ))}
          </div>

          <label className="block text-sm text-slate-300">
            Display name
            <input
              required
              value={displayName}
              onChange={(e) => setDisplayName(e.target.value)}
              className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-slate-100"
              placeholder="deck_host"
            />
          </label>

          {sourceType === "local" ? (
            <label className="block text-sm text-slate-300">
              Local path
              <InfoTip label="Local path derivation">
                MSGF derives a stable <code className="text-cyan-100">project_origin</code> from this
                folder path when you leave the override blank. Use the app folder you open in Cursor —
                not always the monorepo root.
              </InfoTip>
              <input
                required
                value={localPath}
                onChange={(e) => setLocalPath(e.target.value)}
                className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
                placeholder="C:/dev/my-app"
              />
            </label>
          ) : (
            <label className="block text-sm text-slate-300">
              Repo URL
              <input
                required
                type="url"
                value={githubUrl}
                onChange={(e) => setGithubUrl(e.target.value)}
                className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
                placeholder="https://github.com/owner/repository"
              />
            </label>
          )}

          <label className="block text-sm text-slate-300">
            Optional project origin override
            <input
              value={projectOrigin}
              onChange={(e) => setProjectOrigin(e.target.value)}
              className="mt-1 w-full rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 font-mono text-sm text-slate-100"
              placeholder="owner/repo or custom/tag"
            />
          </label>

          {message ? (
            <p className="text-sm text-emerald-300" role="status">
              {message}
            </p>
          ) : null}
          {error ? (
            <p className="text-sm text-amber-200" role="alert">
              {error}
            </p>
          ) : null}

          <button
            type="submit"
            disabled={saving}
            className="w-full rounded-full border border-emerald-500/40 bg-gradient-to-r from-emerald-600/80 to-violet-600/80 px-5 py-2.5 text-sm font-semibold text-white shadow-lg shadow-violet-900/20 transition hover:from-emerald-500 hover:to-violet-500 disabled:opacity-50 sm:w-auto"
          >
            {saving ? "Saving…" : "Save Project Mapping"}
          </button>
        </form>

        <aside className="glass-panel w-full shrink-0 rounded-2xl border border-cyan-500/20 p-5">
          <p className="text-xs font-semibold uppercase tracking-[0.2em] text-cyan-300/90">
            Account scope
          </p>
          <h3 className="mt-2 text-base font-semibold text-slate-100">Infrastructure context</h3>
          <dl className="mt-4 space-y-3 text-sm">
            <div>
              <dt className="text-slate-500">Access role</dt>
              <dd className="font-medium text-cyan-100">{accessRole}</dd>
            </div>
            <div>
              <dt className="text-slate-500">Sandbox status</dt>
              <dd className="font-medium text-slate-200">{companySilo}</dd>
            </div>
            <div>
              <dt className="text-slate-500">Platform roles</dt>
              <dd className="font-medium text-cyan-100">
                {permissions?.roles.join(", ") ?? accessRole}
              </dd>
            </div>
            <div>
              <dt className="text-slate-500">Tenant key</dt>
              <dd className="flex flex-wrap items-center gap-2">
                <span className="break-all font-mono text-xs text-cyan-200/90">{tenantKey}</span>
                <button
                  type="button"
                  onClick={() => void navigator.clipboard.writeText(tenantKey)}
                  className="rounded-lg border border-slate-600 px-2 py-1 text-[11px] text-slate-200 hover:bg-slate-800"
                >
                  Copy key
                </button>
              </dd>
            </div>
          </dl>
          <details className="mt-4 text-xs text-slate-400">
            <summary className="cursor-pointer text-slate-300">Setup guide</summary>
            <p className="mt-2 leading-relaxed">
              BYOK uses Redis, Supabase, and model keys under .msgf/keys/. Managed Pro is on{" "}
              <Link href="/pricing" className="text-violet-300 hover:underline">
                pricing
              </Link>
              .
            </p>
          </details>
        </aside>
      </div>

      {monorepoPresets.length > 0 ? (
        <section className="glass-panel rounded-2xl border border-violet-500/20 p-5 sm:p-6">
          <h3 className="text-base font-semibold text-slate-100">Monorepo shortcuts</h3>
          <p className="mt-1 text-sm text-slate-400">One-click workspace rows for internal apps.</p>
          <ul className="mt-4 space-y-2">
            {monorepoPresets.map((preset) => {
              const mapped = projects.some((p) => p.project_origin === preset.project_origin);
              return (
                <li
                  key={preset.id}
                  className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-slate-800 px-4 py-3 text-sm"
                >
                  <div className="min-w-0">
                    <p className="font-medium text-slate-100">{preset.display_name}</p>
                    <p className="font-mono text-xs text-slate-500">{preset.project_origin}</p>
                  </div>
                  {mapped ? (
                    <span className="text-xs text-emerald-400">Mapped</span>
                  ) : (
                    <button
                      type="button"
                      disabled={addingPresetId === preset.id}
                      onClick={() => void addMonorepoPreset(preset.id)}
                      className="rounded-full border border-violet-500/40 bg-violet-500/15 px-3 py-1.5 text-xs font-medium text-violet-100 hover:bg-violet-500/25 disabled:opacity-50"
                    >
                      {addingPresetId === preset.id ? "Adding…" : "Add workspace"}
                    </button>
                  )}
                </li>
              );
            })}
          </ul>
        </section>
      ) : presetAudience === "customer" ? (
        <p className="text-sm text-slate-500">
          External accounts map custom projects only — internal monorepo shortcuts are hidden.
        </p>
      ) : null}
            </div>
          </div>
        </div>
      ) : null}

      <section className="glass-panel rounded-2xl border border-violet-500/15 p-5 sm:p-6">
        <h3 className="text-base font-semibold text-slate-100">Mapped projects ({projects.length})</h3>
        {loading ? <p className="mt-3 text-sm text-slate-500">Loading…</p> : null}
        {!loading && projects.length === 0 ? (
          <p className="mt-3 text-sm text-slate-400">
            No projects yet. Download the extension, copy the setup prompt, then add each app.
          </p>
        ) : null}
        <ul className="mt-4 space-y-2">
          {projects.map((project) => (
            <li
              key={project.id}
              className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-slate-800 px-4 py-3 text-sm"
            >
              <div className="min-w-0">
                <p className="font-medium text-slate-100">{project.display_name}</p>
                <p className="font-mono text-xs text-slate-500">{project.project_origin}</p>
                <p className="mt-0.5 text-xs text-slate-500">
                  Last Pulse {activity[project.project_origin]?.last_pulse_at ?? "—"} · Last verify{" "}
                  {activity[project.project_origin]?.last_verify_at ?? "—"} · Sentry quarantine{" "}
                  {activity[project.project_origin]?.sentry_quarantine_count ?? 0}
                </p>
                <p className="mt-0.5 truncate text-xs text-slate-600">
                  {project.source_type === "local" ? project.local_path : project.github_url}
                </p>
              </div>
              <button
                type="button"
                onClick={() => void handleDelete(project.id)}
                className="shrink-0 text-xs text-rose-300 underline-offset-4 hover:underline"
              >
                Remove
              </button>
            </li>
          ))}
        </ul>
      </section>

      <WorkspaceOnboardingPack />

      <section className="space-y-2">
        <h2 className="text-base font-semibold text-slate-100">
          {highlightOrigin ? "Model routing for this project" : "Tenant default model routing"}
        </h2>
        <p className="text-sm text-slate-400">
          {highlightOrigin
            ? `Editing ${highlightOrigin}. A project with no saved row keeps the tenant default.`
            : "All Projects uses this tenant default. Choose a project in the top bar to override it."}
        </p>
        <ConsensusPresetPanel tenantId={tenantKey} projectOrigin={highlightOrigin ?? ""} />
      </section>
    </div>
  );
}
