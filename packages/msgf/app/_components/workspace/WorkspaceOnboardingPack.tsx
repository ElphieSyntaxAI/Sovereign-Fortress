import { useCallback, useEffect, useState } from "react";

import { CollapsiblePanel } from "@/app/_components/workspace/workspace-ui";
import type { OnboardingDocumentMeta } from "@/lib/services/tenant-onboarding-vault";

export function WorkspaceOnboardingPack() {
  const [open, setOpen] = useState(true);
  const [docs, setDocs] = useState<OnboardingDocumentMeta[]>([]);
  const [loading, setLoading] = useState(true);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const res = await fetch("/api/msgf/workspace/onboarding-pack", {
        credentials: "include",
        cache: "no-store",
      });
      const json = (await res.json()) as { ok?: boolean; documents?: OnboardingDocumentMeta[] };
      setDocs(json.documents ?? []);
    } catch {
      setDocs([]);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  if (loading || docs.length === 0) return null;

  return (
    <section className="glass-panel rounded-2xl border border-cyan-500/25 p-4 sm:p-5">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        className="flex w-full items-center justify-between text-left"
      >
        <div>
          <p className="text-sm font-semibold text-cyan-100">Your Onboarding Pack</p>
          <p className="text-xs text-slate-500">{docs.length} secure document(s) from your admin</p>
        </div>
        <span className="text-slate-500">{open ? "−" : "+"}</span>
      </button>
      <CollapsiblePanel open={open}>
        <ul className="mt-4 space-y-2">
          {docs.map((doc) => (
            <li
              key={doc.id}
              className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-slate-800 px-3 py-2 text-sm"
            >
              <div>
                <p className="font-medium text-slate-100">{doc.display_name}</p>
                <p className="text-[11px] uppercase text-slate-500">{doc.kind.replace(/_/g, " ")}</p>
              </div>
              <span className="text-xs text-slate-500">View in workspace after sign-in</span>
            </li>
          ))}
        </ul>
      </CollapsiblePanel>
    </section>
  );
}
