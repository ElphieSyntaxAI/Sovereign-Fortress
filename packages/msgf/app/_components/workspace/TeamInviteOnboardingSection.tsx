import { useCallback, useRef, useState } from "react";

import { InfoTip } from "@/app/_components/workspace/workspace-ui";

export type OnboardingFormState = {
  includePillarGuide: boolean;
  includeArchitectureTemplate: boolean;
  enforceDocusign: boolean;
  customDocumentIds: string[];
  attachedFiles: Array<{ id: string; display_name: string }>;
};

type Props = {
  value: OnboardingFormState;
  onChange: (next: OnboardingFormState) => void;
  uploading?: boolean;
};

export function TeamInviteOnboardingSection({ value, onChange, uploading = false }: Props) {
  const fileRef = useRef<HTMLInputElement>(null);
  const [uploadError, setUploadError] = useState<string | null>(null);

  const patch = useCallback(
    (partial: Partial<OnboardingFormState>) => {
      onChange({ ...value, ...partial });
    },
    [onChange, value]
  );

  async function handleFile(file: File) {
    setUploadError(null);
    const form = new FormData();
    form.append("file", file);
    form.append("display_name", file.name);
    const res = await fetch("/api/msgf/workspace/team/onboarding-documents", {
      method: "POST",
      credentials: "include",
      body: form,
    });
    const json = (await res.json()) as {
      ok?: boolean;
      document?: { id: string; display_name: string };
      error?: string;
    };
    if (!res.ok || !json.ok || !json.document) {
      setUploadError(json.error ?? "Upload failed.");
      return;
    }
    onChange({
      ...value,
      customDocumentIds: [...value.customDocumentIds, json.document.id],
      attachedFiles: [...value.attachedFiles, json.document],
    });
  }

  function removeAttachment(id: string) {
    onChange({
      ...value,
      customDocumentIds: value.customDocumentIds.filter((x) => x !== id),
      attachedFiles: value.attachedFiles.filter((f) => f.id !== id),
    });
  }

  return (
    <div className="rounded-xl border border-slate-800/80 bg-slate-950/40 p-4 sm:p-5">
      <h4 className="text-sm font-semibold text-slate-100">Secure Onboarding Documents</h4>

      <div className="mt-4 space-y-3 text-sm text-slate-300">
        <label className="flex cursor-pointer items-start gap-2">
          <input
            type="checkbox"
            checked={value.includePillarGuide}
            onChange={(e) => patch({ includePillarGuide: e.target.checked })}
            className="mt-1"
          />
          <span>Include Core Pillar Guide</span>
        </label>
        <label className="flex cursor-pointer items-start gap-2">
          <input
            type="checkbox"
            checked={value.includeArchitectureTemplate}
            onChange={(e) => patch({ includeArchitectureTemplate: e.target.checked })}
            className="mt-1"
          />
          <span>Include Architecture Best Practices Template</span>
        </label>
        <label className="flex cursor-pointer items-start gap-2 border-t border-slate-800/80 pt-4">
          <input
            type="checkbox"
            checked={value.enforceDocusign}
            onChange={(e) => patch({ enforceDocusign: e.target.checked })}
            className="mt-1"
          />
          <span className="flex flex-wrap items-center gap-1">
            Enforce DocuSign E-Signature Packet
            <InfoTip label="DocuSign compliance">
              Enabling DocuSign routes the invitee through a secure signing ceremony upon setting up
              their credentials. Their active &apos;dev&apos; or &apos;security&apos; access tokens
              remain locked until a &apos;Completed&apos; webhook is received from DocuSign, ensuring
              total regulatory compliance.
            </InfoTip>
          </span>
        </label>
      </div>

      <div className="mt-4">
        <p className="text-xs font-medium text-slate-400">Upload Custom Tenant PDFs</p>
        <div
          role="button"
          tabIndex={0}
          onKeyDown={(e) => e.key === "Enter" && fileRef.current?.click()}
          onClick={() => fileRef.current?.click()}
          onDragOver={(e) => e.preventDefault()}
          onDrop={(e) => {
            e.preventDefault();
            const f = e.dataTransfer.files?.[0];
            if (f) void handleFile(f);
          }}
          className="mt-2 flex cursor-pointer flex-col items-center justify-center rounded-xl border border-dashed border-violet-500/30 bg-violet-500/5 px-4 py-8 text-center transition hover:border-violet-400/50"
        >
          <p className="text-sm text-slate-300">Drop PDF here or click to select</p>
          <p className="mt-1 text-xs text-slate-500">e.g. security_policy.pdf</p>
          <input
            ref={fileRef}
            type="file"
            accept="application/pdf"
            className="hidden"
            onChange={(e) => {
              const f = e.target.files?.[0];
              if (f) void handleFile(f);
              e.target.value = "";
            }}
          />
        </div>
        {uploading ? <p className="mt-2 text-xs text-slate-500">Uploading…</p> : null}
        {uploadError ? (
          <p className="mt-2 text-xs text-amber-200" role="alert">
            {uploadError}
          </p>
        ) : null}
        {value.attachedFiles.length > 0 ? (
          <ul className="mt-3 space-y-1">
            {value.attachedFiles.map((f) => (
              <li
                key={f.id}
                className="flex items-center justify-between rounded-lg border border-slate-800 px-3 py-2 text-xs"
              >
                <span className="truncate text-slate-200">{f.display_name}</span>
                <button
                  type="button"
                  onClick={() => removeAttachment(f.id)}
                  className="text-rose-300 hover:underline"
                >
                  Remove
                </button>
              </li>
            ))}
          </ul>
        ) : null}
      </div>

      <p className="mt-4 text-xs leading-relaxed text-slate-500">
        <InfoTip label="Vault storage">
          Documents attached here are stored cryptographically inside your tenant Vault. They are
          served securely to the invitee upon successful password configuration, ensuring your
          internal architecture documentation never leaks over public email channels.
        </InfoTip>
      </p>
    </div>
  );
}
