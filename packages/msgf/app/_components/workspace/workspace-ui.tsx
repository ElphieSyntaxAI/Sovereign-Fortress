export function CollapsiblePanel({
  open,
  children,
  id,
}: {
  open: boolean;
  children: ReactNode;
  id?: string;
}) {
  return (
    <div
      id={id}
      className={`grid transition-[grid-template-rows] duration-300 ease-in-out motion-reduce:transition-none ${
        open ? "grid-rows-[1fr]" : "grid-rows-[0fr]"
      }`}
    >
      <div className="overflow-hidden">{children}</div>
    </div>
  );
}

export function CopyField({
  label,
  value,
  mono = true,
}: {
  label: string;
  value: string;
  mono?: boolean;
}) {
  const [copied, setCopied] = useState(false);

  const onCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }, [value]);

  return (
    <div className="space-y-1.5">
      <div className="flex items-center justify-between gap-2">
        <span className="text-xs font-medium text-slate-400">{label}</span>
        <button
          type="button"
          onClick={() => void onCopy()}
          className="rounded-md border border-slate-600/60 bg-slate-800/60 px-2.5 py-1 text-xs font-medium text-slate-200 transition hover:bg-slate-700/80"
        >
          {copied ? "Copied" : "Copy"}
        </button>
      </div>
      <pre
        className={`max-h-56 overflow-auto rounded-lg border border-slate-700/60 bg-slate-950/80 p-3 text-xs text-emerald-100/90 ${mono ? "font-mono" : ""}`}
      >
        {value}
      </pre>
    </div>
  );
}

export function StepBadge({ n, done }: { n: number; done?: boolean }) {
  return (
    <span
      className={`flex h-9 w-9 shrink-0 items-center justify-center rounded-full text-sm font-bold ${
        done
          ? "bg-emerald-500/20 text-emerald-200 ring-1 ring-emerald-400/40"
          : "bg-violet-500/15 text-violet-200 ring-1 ring-violet-400/30"
      }`}
    >
      {done ? "✓" : n}
    </span>
  );
}

