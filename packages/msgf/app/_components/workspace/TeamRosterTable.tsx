import type { TeamRosterRow } from "@/lib/services/company-team";

type Props = {
  rows: TeamRosterRow[];
  loading?: boolean;
};

function IntegrationPill({ status }: { status: TeamRosterRow["integration_status"] }) {
  const styles =
    status === "connected"
      ? "border-emerald-500/40 bg-emerald-500/15 text-emerald-200"
      : status === "partial"
        ? "border-amber-500/40 bg-amber-500/15 text-amber-200"
        : "border-slate-600 bg-slate-800/60 text-slate-400";
  return (
    <span className={`rounded-full border px-2 py-0.5 text-[11px] font-medium capitalize ${styles}`}>
      {status}
    </span>
  );
}

function CompliancePill({ status }: { status: TeamRosterRow["compliance_status"] }) {
  if (status === "n/a") return <span className="text-xs text-slate-600">N/A</span>;
  const styles =
    status === "active"
      ? "border-emerald-500/40 text-emerald-300"
      : "border-amber-500/40 text-amber-200";
  return (
    <span className={`rounded-full border px-2 py-0.5 text-[11px] font-medium ${styles}`}>
      {status === "pending_signatures" ? "Pending Signatures" : "Active"}
    </span>
  );
}

export function TeamRosterTable({ rows, loading }: Props) {
  if (loading) return <p className="text-sm text-slate-500">Loading roster…</p>;
  if (!rows.length) {
    return <p className="text-sm text-slate-500">No team members yet — send an invitation below.</p>;
  }

  return (
    <div className="overflow-x-auto rounded-xl border border-slate-800/80">
      <table className="min-w-full divide-y divide-slate-800 text-sm">
        <thead className="bg-slate-950/60 text-left text-xs uppercase tracking-wide text-slate-500">
          <tr>
            <th className="px-4 py-3 font-medium">User Email</th>
            <th className="px-4 py-3 font-medium">Platform Role</th>
            <th className="px-4 py-3 font-medium">Assigned Origins</th>
            <th className="px-4 py-3 font-medium">Integration</th>
            <th className="px-4 py-3 font-medium">Compliance</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-slate-800/80">
          {rows.map((row) => (
            <tr key={row.user_id} className="text-slate-300">
              <td className="px-4 py-3">{row.email}</td>
              <td className="px-4 py-3 capitalize">{row.team_platform_role ?? "—"}</td>
              <td className="max-w-[12rem] px-4 py-3">
                <span className="line-clamp-2 text-xs text-slate-400">
                  {(row.project_labels.length ? row.project_labels : row.project_origins).join(", ") ||
                    "—"}
                </span>
              </td>
              <td className="px-4 py-3">
                <IntegrationPill status={row.integration_status} />
              </td>
              <td className="px-4 py-3">
                <CompliancePill status={row.compliance_status} />
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
