import { useEffect, useState } from "react";
import { usePathname, useRouter, useSearchParams } from "next/navigation";

type Props = {
  id?: string;
};

export function OpsProjectOriginStrip({ id }: Props) {
  const router = useRouter();
  const pathname = usePathname();
  const searchParams = useSearchParams();
  const fromUrl = searchParams?.get("project_origin")?.trim() || "";
  const [value, setValue] = useState(fromUrl);

  useEffect(() => {
    setValue(fromUrl);
  }, [fromUrl]);

  function apply() {
    const next = new URLSearchParams(searchParams?.toString() ?? "");
    const trimmed = value.trim();
    if (trimmed) next.set("project_origin", trimmed);
    else next.delete("project_origin");
    const qs = next.toString();
    const hash = typeof window !== "undefined" ? window.location.hash : "";
    router.replace(`${pathname}${qs ? `?${qs}` : ""}${hash || ""}`);
  }

  return (
    <section
      id={id}
      className="glass-panel rounded-2xl border border-slate-600/30 p-4 sm:p-5"
      aria-label="Shared project filter"
    >
      <label className="block text-xs font-semibold uppercase tracking-[0.18em] text-slate-400">
        Shared project filter
      </label>
      <div className="mt-3 flex flex-wrap gap-2">
        <input
          value={value}
          onChange={(e) => setValue(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter") apply();
          }}
          placeholder="project_origin"
          className="min-w-[16rem] flex-1 rounded-lg border border-slate-700 bg-slate-950/60 px-3 py-2 text-sm text-slate-100"
        />
        <button
          type="button"
          onClick={apply}
          className="rounded-lg bg-violet-600/80 px-3 py-2 text-sm font-medium text-white hover:bg-violet-500"
        >
          Apply
        </button>
      </div>
    </section>
  );
}
