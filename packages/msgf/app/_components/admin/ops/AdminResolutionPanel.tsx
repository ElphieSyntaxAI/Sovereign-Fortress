import { useEffect, useState } from "react";

import {
  enrichedToAdminRemediationStrategy,
  remediationStrategiesForBugIndex,
} from "@/lib/admin-decision-portal";
import {
  approveIncident,
  buildMitigationAction,
  fetchAdminNarrativeLog,
  fetchIncidentRemediationStrategies,
  PulseTiebreakFailedError,
  PULSE_TIEBREAK_FAILED_TOAST,
  rejectIncident,
  type AdminRemediationStrategy,
  type MsgfIncident,
} from "@/lib/admin-browser-api";
import { PillarHaltBanner } from "./PillarHaltBanner";
import { AdminStrategyMatrix } from "./AdminStrategyMatrix";

type Props = {
  incident: MsgfIncident;
  detail: string;
  onApproved: (incident: MsgfIncident) => void;
  /** Only global operators may register Global Fix / DNA promotion. */
  canPromoteToGlobal?: boolean;
  /**
   * When true (global operator dashboard), do not load narrative logs that contain raw keystrokes.
   */
  hideDeveloperKeystrokes?: boolean;
};

function formatEvidenceBlock(log: {
  keystrokes_plain_text: string | null;
  models_disagree: Record<string, unknown> | null;
}): string {
  const sections: string[] = [];

  sections.push("=== keystrokes_plain_text ===");
  sections.push(log.keystrokes_plain_text?.trim() || "(not recorded for this log)");

  sections.push("");
  sections.push("=== metadata.models_disagree ===");
  sections.push(
    log.models_disagree
      ? JSON.stringify(log.models_disagree, null, 2)
      : "(not recorded for this log)"
  );

  return sections.join("\n");
}

export function AdminResolutionPanel({
  incident,
  detail,
  onApproved,
  canPromoteToGlobal = true,
  hideDeveloperKeystrokes = false,
}: Props) {
  const [matrixStrategies, setMatrixStrategies] = useState<AdminRemediationStrategy[]>([]);
  const [selectedStrategyIndex, setSelectedStrategyIndex] = useState<number | null>(null);
  const [strategiesLoading, setStrategiesLoading] = useState(false);
  const [strategiesError, setStrategiesError] = useState<string | null>(null);

  const [approvedDelta, setApprovedDelta] = useState("");
  const [operatorNote, setOperatorNote] = useState("");
  const [rejectReason, setRejectReason] = useState("Policy Violation");
  const [applyToAllFutureSessions, setApplyToAllFutureSessions] = useState(false);
  const [busy, setBusy] = useState(false);
  const [busyAction, setBusyAction] = useState<"approve" | "reject" | null>(null);
  const [status, setStatus] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [evidenceText, setEvidenceText] = useState<string | null>(null);
  const [evidenceLoading, setEvidenceLoading] = useState(false);
  const [evidenceError, setEvidenceError] = useState<string | null>(null);
  const [toast, setToast] = useState<string | null>(null);

  function selectStrategy(strategy: AdminRemediationStrategy, index: number) {
    setSelectedStrategyIndex(index);
    setApprovedDelta(strategy.fixTemplate);
    if (!canPromoteToGlobal) {
      setApplyToAllFutureSessions(false);
    } else if (strategy.applyToFutureSessions != null) {
      setApplyToAllFutureSessions(strategy.applyToFutureSessions);
    } else if (strategy.scope === "global") {
      setApplyToAllFutureSessions(true);
    } else if (strategy.scope === "local") {
      setApplyToAllFutureSessions(false);
    }
    setError(null);
  }

  useEffect(() => {
    let cancelled = false;
    setStrategiesLoading(true);
    setStrategiesError(null);
    setMatrixStrategies([]);
    setSelectedStrategyIndex(null);
    setApprovedDelta("");

    void (async () => {
      try {
        const { strategies } = await fetchIncidentRemediationStrategies(incident.id);
        if (cancelled) return;

        if (strategies.length > 0) {
          setMatrixStrategies(strategies);
          setSelectedStrategyIndex(0);
          setApprovedDelta(strategies[0].fixTemplate);
          return;
        }

        const fallback = remediationStrategiesForBugIndex(
          incident.bug_index,
          incident.strategies?.strategies
        ).map(enrichedToAdminRemediationStrategy);

        if (cancelled) return;
        setMatrixStrategies(fallback);
        if (fallback.length > 0) {
          setSelectedStrategyIndex(0);
          setApprovedDelta(fallback[0].fixTemplate);
        }
      } catch (e) {
        if (cancelled) return;

        const fallback = remediationStrategiesForBugIndex(
          incident.bug_index,
          incident.strategies?.strategies
        ).map(enrichedToAdminRemediationStrategy);

        setStrategiesError(
          e instanceof Error ? e.message : "Failed to load remediation strategies."
        );
        setMatrixStrategies(fallback);
        if (fallback.length > 0) {
          setSelectedStrategyIndex(0);
          setApprovedDelta(fallback[0].fixTemplate);
        }
      } finally {
        if (!cancelled) setStrategiesLoading(false);
      }
    })();

    return () => {
      cancelled = true;
    };
  }, [incident.id, incident.bug_index, incident.strategies]);

  useEffect(() => {
    if (canPromoteToGlobal === false) {
      setApplyToAllFutureSessions(false);
    }
  }, [canPromoteToGlobal]);

  useEffect(() => {
    setOperatorNote("");
    setRejectReason("Policy Violation");
    setApplyToAllFutureSessions(false);
    setStatus(null);
    setError(null);
    setToast(null);
  }, [incident.id]);

  useEffect(() => {
    if (hideDeveloperKeystrokes) {
      setEvidenceText(null);
      setEvidenceError(null);
      setEvidenceLoading(false);
      return;
    }

    setEvidenceText(null);
    setEvidenceError(null);

    const logId = incident.narrative_log_id;
    if (!logId) {
      setEvidenceError("No narrative_log_id on this incident.");
      return;
    }

    let cancelled = false;
    setEvidenceLoading(true);

    void (async () => {
      try {
        const log = await fetchAdminNarrativeLog(logId);
        if (cancelled) return;
        setEvidenceText(formatEvidenceBlock(log));
      } catch (e) {
        if (cancelled) return;
        setEvidenceError(
          e instanceof Error ? e.message : "Failed to load narrative log evidence."
        );
      } finally {
        if (!cancelled) setEvidenceLoading(false);
      }
    })();

    return () => {
      cancelled = true;
    };
  }, [incident.id, incident.narrative_log_id, hideDeveloperKeystrokes]);

  async function handleApprove() {
    const delta = approvedDelta.trim();
    if (!delta) {
      setError("Select a remediation strategy before approving.");
      return;
    }

    setBusy(true);
    setBusyAction("approve");
    setError(null);
    setToast(null);
    setStatus("Running Pulse tie-break (POST /api/msgf/pulse)…");

    try {
      const selectedStrategy =
        selectedStrategyIndex != null
          ? matrixStrategies[selectedStrategyIndex]
          : undefined;
      const strategyLabel = selectedStrategy?.label;

      const mitigationAction = buildMitigationAction({
        applyToAllFutureSessions,
        incident,
        strategy: selectedStrategy,
        fixTemplate: delta,
      });

      const { incident: resolved, pulse } = await approveIncident({
        incident,
        approvedDelta: delta,
        operatorNote: operatorNote.trim() || undefined,
        remediationStrategyLabel: strategyLabel,
        applyToAllFutureSessions,
        mitigationAction,
      });

      const ledger =
        typeof pulse.ledger === "string" ? pulse.ledger : "unknown";
      const globalMsg = applyToAllFutureSessions
        ? " Global Fix registered in MSGF rules + P2 education Vault."
        : "";
      setStatus(`Done — incident resolved; Pulse ledger: ${ledger}.${globalMsg}`);
      onApproved(resolved);
    } catch (e) {
      if (e instanceof PulseTiebreakFailedError) {
        setToast(PULSE_TIEBREAK_FAILED_TOAST);
        setError(null);
      } else {
        setError(e instanceof Error ? e.message : "Approval failed.");
      }
      setStatus(null);
    } finally {
      setBusy(false);
      setBusyAction(null);
    }
  }

  async function handleReject() {
    setBusy(true);
    setBusyAction("reject");
    setError(null);
    setStatus("Rejecting incident (PATCH)…");

    try {
      const { incident: resolved, authorNotified, authorNotifySkipped } =
        await rejectIncident({
          incident,
          reason: rejectReason.trim() || "Policy Violation",
          notifyAuthor: true,
        });

      const notifyMsg = authorNotified
        ? " Author app notified."
        : authorNotifySkipped
          ? ` Author notify skipped: ${authorNotifySkipped}`
          : "";
      setStatus(`Rejected — incident resolved.${notifyMsg}`);
      onApproved(resolved);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Rejection failed.");
      setStatus(null);
    } finally {
      setBusy(false);
      setBusyAction(null);
    }
  }

  return (
    <div className="relative flex flex-col gap-4 rounded-xl border border-zinc-800 bg-gradient-to-b from-zinc-900/80 to-zinc-950/90 p-4 shadow-lg shadow-black/20">
      {toast ? (
        <div
          role="status"
          className="fixed bottom-6 right-6 z-50 max-w-sm rounded-lg border border-amber-700/80 bg-amber-950 px-4 py-3 text-sm text-amber-100 shadow-lg shadow-black/40"
        >
          {toast}
        </div>
      ) : null}
      <header>
        <p className="text-[10px] font-semibold uppercase tracking-[0.2em] text-violet-400/90">
          Decision portal
        </p>
        <h3 className="mt-1 text-base font-semibold text-zinc-50">Operator resolution</h3>
        <p className="mt-1 text-xs text-zinc-500">
          Review halt pillar, model evidence, and remediation consequences — then commit via
          Pulse tie-break or admin reject.
        </p>
      </header>

      <PillarHaltBanner bugIndex={incident.bug_index} />

      <details className="group rounded-lg border border-zinc-800/80 bg-zinc-950/50">
        <summary className="cursor-pointer px-3 py-2 text-xs font-medium text-zinc-400 hover:text-zinc-200">
          Incident metadata
        </summary>
        <pre className="max-h-28 overflow-auto border-t border-zinc-800 px-3 py-2 text-[11px] leading-relaxed text-zinc-400 whitespace-pre-wrap">
          {detail}
        </pre>
      </details>

      <div>
        <p className="text-xs font-medium text-zinc-400">Pulse evidence</p>
        {hideDeveloperKeystrokes ? (
          <p className="mt-2 rounded-md border border-zinc-800 bg-zinc-950/80 px-3 py-2 text-xs leading-relaxed text-zinc-500">
            Raw developer keystrokes and narrative payloads are hidden on the global operator view.
            Decisions use HITL remediation strategies, bug index, and company-validated logic deltas
            only.
          </p>
        ) : evidenceLoading ? (
          <p className="mt-2 text-xs text-zinc-500">Loading narrative log…</p>
        ) : evidenceError ? (
          <p className="mt-2 text-xs text-amber-400/90">{evidenceError}</p>
        ) : (
          <pre className="mt-2 max-h-48 overflow-auto rounded-md border border-zinc-700/80 bg-zinc-950 p-3 font-mono text-[11px] leading-relaxed text-zinc-300 whitespace-pre-wrap">
            {evidenceText ?? ""}
          </pre>
        )}
      </div>

      <AdminStrategyMatrix
        strategies={matrixStrategies}
        selectedIndex={selectedStrategyIndex}
        onSelect={selectStrategy}
        loading={strategiesLoading}
        error={strategiesError}
      />

      <label className="block text-xs text-zinc-400">
        Approved delta (Pulse override)
        <textarea
          value={approvedDelta}
          onChange={(e) => setApprovedDelta(e.target.value)}
          rows={4}
          placeholder="Select a strategy card or type the operator-approved delta…"
          className="mt-1 w-full rounded-md border border-zinc-700 bg-zinc-950 px-2 py-2 font-mono text-sm leading-relaxed text-zinc-100"
        />
      </label>

      <label
        className={`flex cursor-pointer items-start gap-2 rounded-lg border px-3 py-2.5 text-xs text-zinc-300 ${
          canPromoteToGlobal
            ? "border-violet-900/40 bg-violet-950/20"
            : "cursor-not-allowed border-zinc-800/80 bg-zinc-900/30 opacity-70"
        }`}
      >
        <input
          type="checkbox"
          checked={applyToAllFutureSessions}
          disabled={!canPromoteToGlobal}
          onChange={(e) => setApplyToAllFutureSessions(e.target.checked)}
          className="mt-0.5 rounded border-zinc-600 disabled:opacity-50"
        />
        <span>
          <span className="font-medium text-violet-200">Apply to all future sessions</span>
          <span className="mt-0.5 block text-[11px] text-zinc-500">
            {canPromoteToGlobal
              ? "Registers a Global Fix in MSGF rules and writes a P2 education Vault entry so the Brain prioritizes this operator correction on future Pulses."
              : "Only global operators can promote fixes to global DNA. Company operators apply session-scoped mitigations only."}
          </span>
        </span>
      </label>

      <label className="block text-xs text-zinc-400">
        Operator note (optional)
        <input
          type="text"
          value={operatorNote}
          onChange={(e) => setOperatorNote(e.target.value)}
          placeholder="Approved by ops — HITL cleared"
          className="mt-1 w-full rounded-md border border-zinc-700 bg-zinc-950 px-2 py-1.5 text-sm text-zinc-100"
        />
      </label>

      <label className="block text-xs text-zinc-400">
        Rejection reason
        <input
          type="text"
          value={rejectReason}
          onChange={(e) => setRejectReason(e.target.value)}
          placeholder="Policy Violation"
          className="mt-1 w-full rounded-md border border-zinc-700 bg-zinc-950 px-2 py-1.5 text-sm text-zinc-100"
        />
      </label>

      {error ? (
        <p className="text-xs text-red-400">{error}</p>
      ) : status ? (
        <p
          className={`text-xs ${
            busyAction === "reject" ? "text-amber-400/90" : "text-emerald-400/90"
          }`}
        >
          {status}
        </p>
      ) : null}

      <div className="flex flex-wrap gap-2 border-t border-zinc-800/80 pt-3">
        <button
          type="button"
          onClick={() => void handleApprove()}
          disabled={busy || !approvedDelta.trim()}
          className="rounded-md bg-emerald-800 px-4 py-2 text-sm font-medium text-emerald-50 hover:bg-emerald-700 disabled:opacity-50"
        >
          {busyAction === "approve" ? "Approving…" : "Approve override"}
        </button>
        <button
          type="button"
          onClick={() => void handleReject()}
          disabled={busy}
          className="rounded-md border border-red-900/60 bg-red-950/50 px-4 py-2 text-sm font-medium text-red-100 hover:bg-red-900/40 disabled:opacity-50"
        >
          {busyAction === "reject" ? "Rejecting…" : "Reject"}
        </button>
      </div>
    </div>
  );
}
