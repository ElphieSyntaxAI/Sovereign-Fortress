import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

import type { MyEcoUsageResponse } from "@/lib/services/my-eco-usage";
import { CO2_LBS_PER_TREE_SEEDLING_10_YEARS } from "@/lib/utils/ecoEquivalencies";

function formatBillions(tokens: number): string {
  return (tokens / 1_000_000_000).toLocaleString(undefined, { maximumFractionDigits: 3 });
}

function formatNum(value: number, max = 2): string {
  return value.toLocaleString(undefined, { maximumFractionDigits: max });
}

export function UserBlueprintEcoPanel() {
  const [data, setData] = useState<MyEcoUsageResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch("/api/msgf/eco/my-usage", { credentials: "include", cache: "no-store" });
      const json = (await res.json()) as MyEcoUsageResponse | { ok: false; error: string };
      if (!res.ok || !("ok" in json) || json.ok !== true) {
        throw new Error("error" in json ? json.error : `HTTP ${res.status}`);
      }
      setData(json);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Failed to load your blueprint.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  const treeEquivalent = data
    ? data.user_total.metrics.co2e_offset_lbs / CO2_LBS_PER_TREE_SEEDLING_10_YEARS
    : 0;

  return (
    <section className="glass-panel space-y-6 rounded-2xl border border-cyan-500/20 p-5 sm:p-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <p className="text-[11px] font-semibold uppercase tracking-[0.22em] text-cyan-300/90">
            Your local blueprint
          </p>
          <h2 className="mt-2 text-xl font-bold tracking-tight text-slate-50 sm:text-2xl">
            Sustainable compute across your repositories
          </h2>
          <p className="mt-2 max-w-2xl text-sm text-slate-400">
            Public marketing totals show the global Elphie Syntax network. This dashboard reflects
            only your mapped local projects and GitHub repositories.
          </p>
        </div>
        <Link
          href="/setup/projects"
          className="rounded-full border border-cyan-500/30 bg-cyan-500/10 px-4 py-2 text-sm font-medium text-cyan-100 transition hover:bg-cyan-500/20"
        >
          Map projects →
        </Link>
      </div>

      {loading ? (
        <p className="text-sm text-slate-500">Loading your environmental blueprint…</p>
      ) : null}

      {error ? (
        <p className="rounded-xl border border-amber-500/30 bg-amber-500/10 px-4 py-3 text-sm text-amber-100">
          {error}
        </p>
      ) : null}

      {data ? (
        <>
          <p className="rounded-2xl border border-emerald-400/20 bg-emerald-500/10 p-4 text-sm font-medium leading-relaxed text-emerald-50">
            Across your mapped work, MSGF has sharded{" "}
            <strong>{formatBillions(data.user_total.metrics.tokens_saved)} Billion</strong> tokens
            locally — contributing{" "}
            <strong>{formatNum(data.user_total.contribution_to_global_pct, 2)}%</strong> of the
            public network total. That prevented{" "}
            <strong>{formatNum(data.user_total.metrics.grid_compute_prevented_kwh, 2)} kWh</strong>{" "}
            of grid power (about <strong>{formatNum(treeEquivalent, 1)}</strong> tree seedlings) and
            conserved{" "}
            <strong>
              {formatNum(data.user_total.metrics.freshwater_conserved_gallons, 2)} gallons
            </strong>{" "}
            of freshwater cooling.
          </p>

          <div className="grid gap-4 sm:grid-cols-3">
            <div className="rounded-xl border border-slate-700/60 bg-slate-950/50 p-4">
              <p className="text-xs uppercase tracking-wider text-slate-500">Global network</p>
              <p className="mt-2 text-lg font-semibold text-slate-100">
                {formatBillions(data.global.metrics.tokens_saved)}B tokens
              </p>
              <p className="mt-1 text-xs text-slate-500">Public marketing context</p>
            </div>
            <div className="rounded-xl border border-cyan-500/25 bg-cyan-500/10 p-4">
              <p className="text-xs uppercase tracking-wider text-cyan-200/80">Your total</p>
              <p className="mt-2 text-lg font-semibold text-cyan-50">
                {data.user_total.metrics.tokens_saved.toLocaleString()} tokens
              </p>
              <p className="mt-1 text-xs text-cyan-200/70">
                {formatNum(data.user_total.contribution_to_global_pct, 2)}% of global CO₂e offset
              </p>
            </div>
            <div className="rounded-xl border border-emerald-500/25 bg-emerald-500/10 p-4">
              <p className="text-xs uppercase tracking-wider text-emerald-200/80">Mapped projects</p>
              <p className="mt-2 text-lg font-semibold text-emerald-50">
                {data.mapped_projects.length}
              </p>
              <p className="mt-1 text-xs text-emerald-200/70">Local paths + GitHub repos</p>
            </div>
          </div>

          {data.mapped_projects.length === 0 ? (
            <p className="text-sm text-slate-400">
              No projects mapped yet.{" "}
              <Link href="/setup/projects" className="text-cyan-300 underline-offset-4 hover:underline">
                Add your first local folder or GitHub repository
              </Link>{" "}
              to scope pillar health and eco metrics to your work only.
            </p>
          ) : (
            <ul className="space-y-2">
              {data.mapped_projects.map((project) => (
                <li
                  key={project.id}
                  className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-slate-800 bg-slate-950/40 px-4 py-3 text-sm"
                >
                  <div>
                    <p className="font-medium text-slate-100">{project.display_name}</p>
                    <p className="text-xs text-slate-500">
                      {project.source_type === "github"
                        ? project.repository_full_name ?? project.github_url
                        : project.local_path}{" "}
                      · <span className="font-mono">{project.project_origin}</span>
                    </p>
                  </div>
                  <span className="rounded-full border border-slate-700 px-2 py-0.5 text-[10px] uppercase tracking-wider text-slate-400">
                    {project.source_type}
                  </span>
                </li>
              ))}
            </ul>
          )}

          {data.projects.length > 0 ? (
            <div className="overflow-x-auto rounded-xl border border-slate-800">
              <table className="min-w-full divide-y divide-slate-800 text-xs">
                <thead className="bg-slate-950/80 text-cyan-300/90">
                  <tr>
                    <th className="px-4 py-3 text-left font-semibold">Project</th>
                    <th className="px-4 py-3 text-right font-semibold">Tokens saved</th>
                    <th className="px-4 py-3 text-right font-semibold">kWh prevented</th>
                    <th className="px-4 py-3 text-right font-semibold">Share of your total</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-900 text-slate-300">
                  {data.projects.map((row) => (
                    <tr key={row.project_origin}>
                      <td className="px-4 py-3">
                        <p className="font-medium text-slate-100">{row.display_name}</p>
                        <p className="font-mono text-[10px] text-slate-500">{row.project_origin}</p>
                      </td>
                      <td className="px-4 py-3 text-right">
                        {row.metrics.tokens_saved.toLocaleString()}
                      </td>
                      <td className="px-4 py-3 text-right">
                        {formatNum(row.metrics.grid_compute_prevented_kwh, 2)}
                      </td>
                      <td className="px-4 py-3 text-right text-cyan-200">
                        {formatNum(row.contribution_pct, 1)}%
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ) : null}
        </>
      ) : null}
    </section>
  );
}
