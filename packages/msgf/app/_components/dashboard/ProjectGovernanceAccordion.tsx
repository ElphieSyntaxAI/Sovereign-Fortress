import { useCallback, useEffect, useMemo, useState } from "react";

import {
  PostIngestHealingConsole,
  type HealConsoleStatus,
} from "@/app/_components/dashboard/PostIngestHealingConsole";
import {
  consolidatedPillarSummary,
  overallLabel,
  PillarCard,
  PillarDrilldown,
  PillarTerminalDrawer,
  statusStyles,
} from "@/app/_components/dashboard/governance-pillar-blocks";
import { GOVERNANCE_PILLAR_CARDS } from "@/lib/dashboard-pillar-copy";
import {
  healthPillarsQuery,
  type DashboardHealthScopeMode,
} from "@/lib/dashboard-health-scope";
import {
  fetchHealQueueForTenant,
  misalignmentCountByPillar,
} from "@/lib/heal-queue-web-client";
import type { HealQueueGetResponse } from "@/lib/schemas/heal-queue";
import type {
  ArbitrationAction,
  ArbitrationStateMachineResult,
  PillarLiveLogs,
  TerminalHardFailureLog,
} from "@/lib/services/dashboard-orchestration";
import type { PillarHealthReport, PillarStoplightStatus } from "@/lib/services/HealthService";
import type { MsgfGovernancePillar } from "@/lib/services/pillar-baseline";

type MappedProject = { project_origin: string; label: string };

type PillarHealthApiResponse = PillarHealthReport & { ok?: boolean; error?: string };

type PillarLogsApiResponse = {
  ok: boolean;
  logs: PillarLiveLogs;
  error?: string;
};

type ArbitrationApiResponse =
  | (ArbitrationStateMachineResult & { source?: "live" | "mock" })
  | { ok: false; error: string };

const LOOKBACK_HOURS = 168;

function logicDriftLabel(trend: PillarHealthReport["logic_drift"]["trend"]): string {
  if (trend === "decreasing") return "Decreasing drift";
  if (trend === "increasing") return "Increasing drift";
  return "Stable";
}

export function ProjectGovernanceAccordion({
  projects,
  healthScope,
  authRedirectPath,
  healQueueTenantId,
  embeddedInAdminPortal,
  onGlobalError,
}: {
  projects: MappedProject[];
  healthScope: DashboardHealthScopeMode;
  authRedirectPath: string;
  healQueueTenantId: string;
  embeddedInAdminPortal: boolean;
  onGlobalError?: (message: string | null) => void;
}) {
  const [expandedOrigin, setExpandedOrigin] = useState<string | null>(
    projects[0]?.project_origin ?? null
  );
  const [reportsByOrigin, setReportsByOrigin] = useState<Record<string, PillarHealthReport>>({});
  const [loadingOrigin, setLoadingOrigin] = useState<string | null>(null);
  const [selectedPillarByOrigin, setSelectedPillarByOrigin] = useState<
    Record<string, MsgfGovernancePillar>
  >(() => {
    const seed: Record<string, MsgfGovernancePillar> = {};
    for (const p of projects) {
      seed[p.project_origin] = "P1";
    }
    return seed;
  });
  const [pillarLogsByOrigin, setPillarLogsByOrigin] = useState<Record<string, PillarLiveLogs | null>>(
    {}
  );
  const [actionResultByOrigin, setActionResultByOrigin] = useState<
    Record<string, ArbitrationStateMachineResult | null>
  >({});
  const [healQueue, setHealQueue] = useState<HealQueueGetResponse | null>(null);
  const [healQueueFetchError, setHealQueueFetchError] = useState<string | null>(null);
  const [healingConsoleOpen, setHealingConsoleOpen] = useState(false);
  const [healConsolePillar, setHealConsolePillar] = useState<MsgfGovernancePillar | null>(null);
  const [healConsoleStatus, setHealConsoleStatus] = useState<HealConsoleStatus>(null);
  const [healConsoleOrigin, setHealConsoleOrigin] = useState<string | null>(null);

  const refreshHealQueue = useCallback(async () => {
    const result = await fetchHealQueueForTenant(healQueueTenantId);
    if (result.ok) {
      setHealQueue(result.data);
      setHealQueueFetchError(null);
    } else {
      setHealQueueFetchError(result.message);
    }
  }, [healQueueTenantId]);

  const fetchProjectReport = useCallback(
    async (projectOrigin: string) => {
      setLoadingOrigin(projectOrigin);
      onGlobalError?.(null);
      try {
        const res = await fetch(healthPillarsQuery(healthScope, LOOKBACK_HOURS, projectOrigin), {
          credentials: "include",
          cache: "no-store",
        });
        if (res.status === 401) {
          window.location.assign(authRedirectPath);
          return;
        }
        const json = (await res.json()) as PillarHealthApiResponse;
        if (!res.ok || json.ok === false) {
          throw new Error(json.error ?? `Health API returned ${res.status}`);
        }
        const { ok: _ok, error: _err, ...nextReport } = json;
        setReportsByOrigin((prev) => ({
          ...prev,
          [projectOrigin]: nextReport as PillarHealthReport,
        }));
      } catch (e) {
        onGlobalError?.(
          e instanceof Error ? e.message : "Failed to refresh project pillar health."
        );
      } finally {
        setLoadingOrigin(null);
      }
    },
    [authRedirectPath, healthScope, onGlobalError]
  );

  useEffect(() => {
    void refreshHealQueue();
  }, [refreshHealQueue]);

  useEffect(() => {
    for (const project of projects) {
      void fetchProjectReport(project.project_origin);
    }
  }, [projects, fetchProjectReport]);

  useEffect(() => {
    const id = window.setInterval(() => {
      for (const project of projects) {
        void fetchProjectReport(project.project_origin);
      }
    }, 30_000);
    return () => window.clearInterval(id);
  }, [projects, fetchProjectReport]);

  const healCountByPillar = useMemo(
    () => misalignmentCountByPillar(healQueue?.remediation_tasks ?? []),
    [healQueue?.remediation_tasks]
  );

  const refreshPillarLogs = useCallback(async (projectOrigin: string, pillar: MsgfGovernancePillar) => {
    const res = await fetch(`/api/msgf/dashboard/pillar/${pillar}`, {
      credentials: "include",
      cache: "no-store",
    });
    const json = (await res.json()) as PillarLogsApiResponse;
    if (res.ok && json.ok) {
      setPillarLogsByOrigin((prev) => ({ ...prev, [projectOrigin]: json.logs }));
    }
  }, []);

  useEffect(() => {
    if (!expandedOrigin) return;
    const pillar = selectedPillarByOrigin[expandedOrigin];
    if (!pillar) return;
    setActionResultByOrigin((prev) => ({ ...prev, [expandedOrigin]: null }));
    void refreshPillarLogs(expandedOrigin, pillar);
  }, [expandedOrigin, selectedPillarByOrigin, refreshPillarLogs]);

  const applyArbitrationAction = useCallback(
    async (projectOrigin: string, failure: TerminalHardFailureLog, action: ArbitrationAction) => {
      const pillar = selectedPillarByOrigin[projectOrigin];
      if (!pillar) return;
      const res = await fetch(`/api/msgf/dashboard/pillar/${pillar}/arbitrate`, {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          incident_id: failure.id,
          action,
          source_string: failure.source_string,
        }),
      });
      const json = (await res.json()) as ArbitrationApiResponse;
      if (!res.ok || !json.ok) {
        onGlobalError?.("error" in json ? json.error : "Failed to apply arbitration action.");
        return;
      }
      setActionResultByOrigin((prev) => ({ ...prev, [projectOrigin]: json }));
      await refreshPillarLogs(projectOrigin, pillar);
    },
    [selectedPillarByOrigin, refreshPillarLogs, onGlobalError]
  );

  const toggleProject = (origin: string) => {
    setExpandedOrigin((prev) => (prev === origin ? null : origin));
  };

  return (
    <section className="space-y-3" aria-label="Projects governance accordion">
      {projects.map((project) => {
        const isOpen = expandedOrigin === project.project_origin;
        const report = reportsByOrigin[project.project_origin] ?? null;
        const summary = report ? consolidatedPillarSummary(report) : "Loading…";
        const stabilityPct = report?.logic_drift.predicted_stability_pct;
        const driftTrend = report?.logic_drift.trend;
        const pendingTotal = report?.pillars.reduce((s, p) => s + p.pending_incidents, 0) ?? 0;
        const hallTotal = report?.pillars.reduce((s, p) => s + p.recent_hall_events, 0) ?? 0;
        const selectedPillarId = selectedPillarByOrigin[project.project_origin] ?? "P1";
        const pillarById = new Map(report?.pillars.map((p) => [p.pillar, p]) ?? []);
        const selectedPillar = pillarById.get(selectedPillarId) ?? report?.pillars[0] ?? null;
        const overallStatus: PillarStoplightStatus = report?.overall_status ?? "green";
        const barStyles = statusStyles(overallStatus);
        const isRefreshing = loadingOrigin === project.project_origin;

        return (
          <article
            key={project.project_origin}
            className={`glass-panel overflow-hidden rounded-2xl border transition-colors duration-300 ${
              isOpen ? "border-violet-500/35" : "border-slate-700/60"
            }`}
          >
            <div className="flex flex-col gap-3 p-4 sm:flex-row sm:items-center sm:justify-between">
              <button
                type="button"
                onClick={() => toggleProject(project.project_origin)}
                className="flex min-w-0 flex-1 flex-col gap-2 text-left"
                aria-expanded={isOpen}
              >
                <div className="flex flex-wrap items-center gap-2">
                  <span
                    className={`inline-flex items-center gap-2 rounded-full border px-2.5 py-1 text-xs font-medium ${barStyles.badge} ${barStyles.ring}`}
                  >
                    <span className={`h-2 w-2 rounded-full ${barStyles.dot}`} aria-hidden />
                    {summary}
                  </span>
                  <h3 className="text-lg font-semibold text-slate-50">{project.label}</h3>
                </div>
                <div className="flex flex-wrap gap-4 text-xs text-slate-400">
                  <span>
                    Stability forecast:{" "}
                    <strong className="text-violet-200">
                      {stabilityPct != null ? `${stabilityPct.toFixed(1)}%` : "—"}
                    </strong>
                  </span>
                  <span>
                    Logic drift:{" "}
                    <strong className="text-amber-200/90">
                      {driftTrend ? logicDriftLabel(driftTrend) : "—"}
                    </strong>
                  </span>
                </div>
              </button>
              <button
                type="button"
                onClick={() => void fetchProjectReport(project.project_origin)}
                disabled={isRefreshing}
                className="shrink-0 rounded-full border border-emerald-500/30 bg-emerald-500/10 px-4 py-2 text-sm font-medium text-emerald-200 transition hover:bg-emerald-500/20 disabled:opacity-50"
              >
                {isRefreshing ? "Refreshing…" : "Refresh now"}
              </button>
            </div>

            <div
              className={`grid transition-[grid-template-rows] duration-300 ease-in-out ${
                isOpen ? "grid-rows-[1fr]" : "grid-rows-[0fr]"
              }`}
            >
              <div className="overflow-hidden">
                <div className="space-y-6 border-t border-slate-800/80 px-4 pb-6 pt-4">
                  {healQueueFetchError ? (
                    <p className="text-sm text-amber-200/90">{healQueueFetchError}</p>
                  ) : null}

                  {report ? (
                    <>
                      <div className="flex flex-wrap gap-3">
                        <div className="rounded-xl border border-amber-500/25 bg-amber-500/10 px-4 py-3">
                          <p className="text-[11px] uppercase tracking-wider text-amber-200/80">
                            Incident queue
                          </p>
                          <p className="mt-1 text-2xl font-semibold text-amber-50">{pendingTotal}</p>
                        </div>
                        <div className="rounded-xl border border-rose-500/25 bg-rose-500/10 px-4 py-3">
                          <p className="text-[11px] uppercase tracking-wider text-rose-200/80">
                            Hall events
                          </p>
                          <p className="mt-1 text-2xl font-semibold text-rose-50">{hallTotal}</p>
                        </div>
                        <div className="rounded-xl border border-violet-500/25 bg-violet-500/10 px-4 py-3">
                          <p className="text-[11px] uppercase tracking-wider text-violet-200/80">
                            Overall
                          </p>
                          <p className="mt-1 text-sm font-semibold text-violet-50">
                            {overallLabel(overallStatus)}
                          </p>
                        </div>
                      </div>

                      <div
                        className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3"
                        aria-label={`Six governance pillars for ${project.label}`}
                      >
                        {GOVERNANCE_PILLAR_CARDS.map((copy) => {
                          const live = pillarById.get(copy.pillar);
                          const healCount = healCountByPillar[copy.pillar];
                          const consoleForThisProject =
                            healingConsoleOpen &&
                            healConsoleOrigin === project.project_origin &&
                            healConsolePillar === copy.pillar;
                          return (
                            <PillarCard
                              key={copy.pillar}
                              pillarId={copy.pillar}
                              title={copy.title}
                              status={live?.status ?? "green"}
                              statusLabel={live?.status_label ?? "Green"}
                              pending={live?.pending_incidents ?? 0}
                              hall={live?.recent_hall_events ?? 0}
                              vault={live?.recent_vault_events ?? 0}
                              summary={live?.summary ?? "No telemetry in lookback window."}
                              selected={selectedPillarId === copy.pillar}
                              healMisalignmentCount={healCount}
                              healConsoleOpen={consoleForThisProject}
                              onSelect={() => {
                                if (healCount > 0) {
                                  if (consoleForThisProject) {
                                    setHealingConsoleOpen(false);
                                    setHealConsolePillar(null);
                                    setHealConsoleOrigin(null);
                                  } else {
                                    setHealConsolePillar(copy.pillar);
                                    setHealConsoleOrigin(project.project_origin);
                                    setHealingConsoleOpen(true);
                                  }
                                } else {
                                  setHealingConsoleOpen(false);
                                  setHealConsolePillar(null);
                                  setHealConsoleOrigin(null);
                                  setSelectedPillarByOrigin((prev) => ({
                                    ...prev,
                                    [project.project_origin]: copy.pillar,
                                  }));
                                }
                              }}
                            />
                          );
                        })}
                      </div>

                      {selectedPillar ? <PillarDrilldown pillar={selectedPillar} /> : null}

                      <PillarTerminalDrawer
                        logs={pillarLogsByOrigin[project.project_origin] ?? null}
                        actionResult={actionResultByOrigin[project.project_origin] ?? null}
                        projectLabel={project.label}
                        onAction={(failure, action) =>
                          applyArbitrationAction(project.project_origin, failure, action)
                        }
                      />

                      <PostIngestHealingConsole
                        open={
                          healingConsoleOpen && healConsoleOrigin === project.project_origin
                        }
                        onClose={() => {
                          setHealingConsoleOpen(false);
                          setHealConsolePillar(null);
                          setHealConsoleOrigin(null);
                        }}
                        tenantId={healQueueTenantId}
                        queue={healQueue}
                        pillarFilter={healConsolePillar}
                        onQueueRefresh={() => void refreshHealQueue()}
                        externalStatus={healConsoleStatus}
                        onStatusChange={setHealConsoleStatus}
                        allowHumanArbitration={embeddedInAdminPortal}
                      />
                    </>
                  ) : (
                    <p className="text-sm text-slate-500">Loading pillar health for this project…</p>
                  )}

                  <p className="text-xs text-slate-600">
                    Lookback {LOOKBACK_HOURS}h · Auto-refresh 30s (global) · Per-project refresh on demand
                  </p>
                </div>
              </div>
            </div>
          </article>
        );
      })}
    </section>
  );
}
