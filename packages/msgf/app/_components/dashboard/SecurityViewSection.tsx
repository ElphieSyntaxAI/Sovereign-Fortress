function SecurityMetricCard({
  label,
  value,
  hint,
  accent = "emerald",
}: {
  label: string;
  value: string | number;
  hint: string;
  accent?: "emerald" | "violet" | "amber" | "rose" | "cyan";
}) {
  const accentBorder =
    accent === "violet"
      ? "border-violet-500/25"
      : accent === "amber"
        ? "border-amber-500/25"
        : accent === "rose"
          ? "border-rose-500/25"
          : accent === "cyan"
            ? "border-cyan-500/25"
            : "border-emerald-500/25";

  return (
    <div className={`rounded-xl border bg-slate-950/50 p-4 ${accentBorder}`}>
      <p className="text-[11px] font-medium uppercase tracking-wider text-slate-500">{label}</p>
      <p className="mt-1 text-2xl font-semibold tabular-nums tracking-tight text-slate-50">{value}</p>
      <p className="mt-1 text-xs leading-snug text-slate-400">{hint}</p>
    </div>
  );
}

function ProtectionStackList({
  items,
}: {
  items: SecuritySnapshot["protection_stack"];
}) {
  if (!items.length) return null;
  return (
    <div className="mt-6 rounded-xl border border-slate-700/50 bg-slate-950/40 p-4">
      <p className="text-xs font-semibold uppercase tracking-wider text-slate-400">Protection stack</p>
      <ul className="mt-3 flex flex-wrap gap-2">
        {items.map((row) => (
          <li
            key={row.id}
            className={`rounded-full border px-2.5 py-1 text-[11px] ${
              row.enabled
                ? "border-emerald-500/30 bg-emerald-500/10 text-emerald-200"
                : "border-slate-600/50 bg-slate-800/50 text-slate-500"
            }`}
            title={row.description}
          >
            {row.enabled ? "on" : "off"} · {row.label}
          </li>
        ))}
      </ul>
    </div>
  );
}

