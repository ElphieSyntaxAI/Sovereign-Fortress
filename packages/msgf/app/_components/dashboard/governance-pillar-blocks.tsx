export function statusStyles(status: PillarStoplightStatus): {
  dot: string;
  ring: string;
  badge: string;
} {
  switch (status) {
    case "green":
      return {
        dot: "bg-emerald-400 shadow-[0_0_12px_rgba(52,211,153,0.55)]",
        ring: "border-emerald-500/30",
        badge: "bg-emerald-500/15 text-emerald-200",
      };
    case "yellow":
    case "yellow_self_healing":
      return {
        dot: "bg-amber-400 shadow-[0_0_12px_rgba(251,191,36,0.45)]",
        ring: "border-amber-500/30",
        badge: "bg-amber-500/15 text-amber-200",
      };
    case "red":
      return {
        dot: "bg-rose-500 shadow-[0_0_12px_rgba(244,63,94,0.55)]",
        ring: "border-rose-500/35",
        badge: "bg-rose-500/15 text-rose-200",
      };
    case "predicted":
      return {
        dot: "bg-violet-400 shadow-[0_0_12px_rgba(167,139,250,0.5)] animate-pulse",
        ring: "border-violet-500/35",
        badge: "bg-violet-500/15 text-violet-200",
      };
    default:
      return {
        dot: "bg-slate-500",
        ring: "border-slate-600/40",
        badge: "bg-slate-500/15 text-slate-300",
      };
  }
}

export function overallLabel(status: PillarStoplightStatus): string {
  switch (status) {
    case "green":
      return "All pillars nominal";
    case "yellow_self_healing":
      return "Elevated — self-healing active";
    case "yellow":
      return "Elevated watch";
    case "red":
      return "Intervention required";
    case "predicted":
      return "Predictive drift alert";
    default:
      return "Unknown";
  }
}

export function consolidatedPillarSummary(report: {
  overall_status: PillarStoplightStatus;
  pillars: { status: PillarStoplightStatus; pending_incidents: number }[];
}): string {
  if (report.overall_status === "green") return "All pillars nominal";
  if (report.pillars.some((p) => p.status === "red")) return "Intervention required";
  if (report.pillars.some((p) => p.pending_incidents > 0)) return "Open incidents";
  return overallLabel(report.overall_status);
}

function summaryRepeatsTitle(summary: string): boolean {
  return /operating normally\.?$/i.test(summary.trim());
}

