function DashboardNavClient({
  userEmail,
  showAdminPortalLink = false,
  showSeed = false,
  primaryLinksOverride,
}: Props) {
  const router = useRouter();
  const pathname = usePathname() ?? "";
  const searchParams = useSearchParams();
  const projectOrigin = searchParams?.get("project_origin")?.trim() ?? "";
  const [signingOut, setSigningOut] = useState(false);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [projectsOpen, setProjectsOpen] = useState(false);
  const [catalogOpen, setCatalogOpen] = useState(false);
  const [developerOpen, setDeveloperOpen] = useState(false);
  const [mobileOpen, setMobileOpen] = useState(false);
  const [projects, setProjects] = useState<ProjectOption[]>([]);
  const settingsRef = useRef<HTMLDivElement>(null);
  const projectsRef = useRef<HTMLDivElement>(null);
  const settingsMenuId = useId();
  const projectsMenuId = useId();
  const mobileDrawerId = useId();

  const primaryLinks = (primaryLinksOverride ?? DASHBOARD_PRIMARY_LINKS).map((link) => ({
    ...link,
    href: withProject(link.href, projectOrigin),
  }));
  const accountLinks = DASHBOARD_ACCOUNT_LINKS;
  const productLinks = DASHBOARD_PRODUCT_LINKS;
  const adminLinks = showAdminPortalLink
    ? [
        ...DASHBOARD_ADMIN_LINKS,
        ...(showSeed
          ? [{ label: "Seed", href: "/admin/seed", matchPath: "/admin/seed" } satisfies DashboardNavLink]
          : []),
      ]
    : [];

  const selectProject = useCallback(
    (origin: string) => {
      const params = new URLSearchParams(searchParams?.toString() ?? "");
      if (origin) params.set("project_origin", origin);
      else params.delete("project_origin");
      const qs = params.toString();
      router.push(qs ? `${pathname}?${qs}` : pathname);
      setProjectsOpen(false);
    },
    [pathname, router, searchParams]
  );

  const signOut = useCallback(async () => {
    setSigningOut(true);
    try {
      const supabase = createClient();
      await supabase.auth.signOut();
      router.replace("/sign-in");
      router.refresh();
    } catch {
      window.location.assign("/sign-in");
    }
  }, [router]);

  const closeAll = useCallback(() => {
    setSettingsOpen(false);
    setProjectsOpen(false);
    setMobileOpen(false);
  }, []);

  useEffect(() => {
    let cancelled = false;
    void fetch("/api/msgf/projects", { credentials: "include" })
      .then((res) => res.json())
      .then((json: { ok?: boolean; projects?: ProjectOption[] }) => {
        if (!cancelled && json.ok && Array.isArray(json.projects)) {
          setProjects(json.projects);
        }
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    if (!settingsOpen && !projectsOpen) return;
    const onPointerDown = (e: PointerEvent) => {
      const target = e.target as Node;
      if (settingsRef.current && !settingsRef.current.contains(target)) {
        setSettingsOpen(false);
      }
      if (projectsRef.current && !projectsRef.current.contains(target)) {
        setProjectsOpen(false);
      }
    };
    const onEscape = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        setSettingsOpen(false);
        setProjectsOpen(false);
        setCatalogOpen(false);
        setDeveloperOpen(false);
      }
    };
    document.addEventListener("pointerdown", onPointerDown);
    document.addEventListener("keydown", onEscape);
    return () => {
      document.removeEventListener("pointerdown", onPointerDown);
      document.removeEventListener("keydown", onEscape);
    };
  }, [settingsOpen, projectsOpen]);

  useEffect(() => {
    if (!mobileOpen) return;
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    const onEscape = (e: KeyboardEvent) => {
      if (e.key === "Escape") setMobileOpen(false);
    };
    document.addEventListener("keydown", onEscape);
    return () => {
      document.body.style.overflow = prev;
      document.removeEventListener("keydown", onEscape);
    };
  }, [mobileOpen]);

  useEffect(() => {
    closeAll();
  }, [pathname, closeAll]);

  return (
    <>
      <header className="sticky top-0 z-50 border-b border-violet-500/10 bg-slate-950/80 backdrop-blur-xl">
        <div className="mx-auto flex h-16 max-w-6xl items-center gap-3 px-4 sm:px-5">
          <Link
            href="/dashboard"
            className="group flex shrink-0 items-center gap-2.5"
            onClick={closeAll}
            aria-label="MSGF governance dashboard"
          >
            <BrandLogo
              size={36}
              decorative
              className="border border-emerald-400/30 bg-emerald-500/10"
            />
            <div className="hidden leading-tight sm:block">
              <span className="block text-sm font-semibold tracking-tight text-slate-100 group-hover:text-emerald-200">
                Elphie Syntax
              </span>
              <span className="block text-[11px] text-slate-500">MSGF dashboard</span>
            </div>
          </Link>

          <nav
            className="hidden min-w-0 flex-1 items-center justify-center gap-0.5 overflow-x-auto md:flex"
            aria-label="Navigation"
          >
            {primaryLinks.map((link) => (
              <Link
                key={link.href}
                href={link.href}
                className={`shrink-0 whitespace-nowrap rounded-full px-2.5 py-1.5 text-sm transition duration-200 xl:px-3 ${
                  isLinkActive(pathname, link)
                    ? link.accent === "amber"
                      ? "bg-amber-500/15 font-medium text-amber-100"
                      : "bg-emerald-500/15 font-medium text-emerald-100"
                    : link.accent === "amber"
                      ? "text-amber-400/90 hover:bg-amber-500/10 hover:text-amber-200"
                      : "text-slate-400 hover:bg-white/5 hover:text-slate-200"
                }`}
              >
                {link.label}
              </Link>
            ))}
          </nav>

          <div className="ml-auto flex shrink-0 items-center gap-1.5 sm:gap-2">
            <div ref={projectsRef} className="relative shrink-0">
              <button
                type="button"
                className="flex max-w-[9rem] items-center gap-1.5 rounded-full border border-slate-700/80 bg-slate-900/70 px-2.5 py-1.5 text-sm text-slate-200 hover:border-emerald-500/40 sm:max-w-[12rem] sm:px-3"
                aria-expanded={projectsOpen}
                aria-controls={projectsMenuId}
                aria-haspopup="listbox"
                onClick={() => setProjectsOpen((open) => !open)}
              >
                <span className="truncate">
                  {projectOrigin
                    ? projects.find((p) => p.project_origin === projectOrigin)?.display_name?.trim() ||
                      projectOrigin
                    : "All Projects"}
                </span>
                <span aria-hidden className="text-slate-500">
                  ▾
                </span>
              </button>
              {projectsOpen ? (
                <div
                  id={projectsMenuId}
                  role="listbox"
                  className="absolute right-0 top-[calc(100%+0.4rem)] z-50 max-h-80 w-64 overflow-y-auto rounded-xl border border-slate-700 bg-slate-950 p-1.5 shadow-xl"
                >
                  <button
                    type="button"
                    role="option"
                    aria-selected={!projectOrigin}
                    className="block w-full rounded-lg px-3 py-2 text-left text-sm text-slate-200 hover:bg-white/5"
                    onClick={() => selectProject("")}
                  >
                    All Projects
                  </button>
                  {projectOrigin && !projects.some((p) => p.project_origin === projectOrigin) ? (
                    <button
                      type="button"
                      role="option"
                      aria-selected
                      className="block w-full truncate rounded-lg px-3 py-2 text-left text-sm text-emerald-100 hover:bg-white/5"
                      onClick={() => selectProject(projectOrigin)}
                    >
                      {projectOrigin}
                    </button>
                  ) : null}
                  {projects.map((project) => (
                    <button
                      key={project.project_origin}
                      type="button"
                      role="option"
                      aria-selected={project.project_origin === projectOrigin}
                      className="block w-full truncate rounded-lg px-3 py-2 text-left text-sm text-slate-200 hover:bg-white/5"
                      onClick={() => selectProject(project.project_origin)}
                    >
                      {project.display_name?.trim() || project.project_origin}
                    </button>
                  ))}
                  <Link
                    href="/workspace?tab=projects"
                    className="mt-1 block border-t border-slate-800 px-3 py-2 text-sm text-emerald-300 hover:bg-white/5"
                    onClick={() => setProjectsOpen(false)}
                  >
                    Connect New Project
                  </Link>
                </div>
              ) : null}
            </div>
            <div ref={settingsRef} className="relative">
              <button
                type="button"
                className={`flex h-10 w-10 items-center justify-center rounded-full border transition duration-200 ${
                  settingsOpen
                    ? "border-violet-400/50 bg-violet-500/20 text-violet-100"
                    : "border-slate-600/50 bg-slate-900/60 text-slate-300 hover:border-violet-500/35 hover:bg-violet-500/10 hover:text-violet-100"
                }`}
                aria-expanded={settingsOpen}
                aria-haspopup="menu"
                aria-controls={settingsMenuId}
                aria-label={settingsOpen ? "Close settings menu" : "Open settings menu"}
                onPointerDown={(e) => e.stopPropagation()}
                onClick={() => setSettingsOpen((o) => !o)}
              >
                <span className="sr-only">Settings and account</span>
                <GearIcon />
              </button>

              <div
                id={settingsMenuId}
                role="menu"
                className={`absolute right-0 top-[calc(100%+0.5rem)] z-50 min-w-[15rem] origin-top-right rounded-xl border border-violet-500/20 bg-slate-950/95 p-1.5 shadow-xl shadow-black/40 backdrop-blur-xl transition-all duration-200 ${
                  settingsOpen
                    ? "pointer-events-auto translate-y-0 scale-100 opacity-100"
                    : "pointer-events-none -translate-y-1 scale-95 opacity-0"
                }`}
              >
                <MenuLabel>Account</MenuLabel>
                {accountLinks.map((link) => (
                  <SettingsItem key={link.href} link={link} onClick={() => setSettingsOpen(false)} />
                ))}
                <MenuLabel>Product</MenuLabel>
                {productLinks.map((link) => (
                  <SettingsItem key={link.href} link={link} onClick={() => setSettingsOpen(false)} />
                ))}
                <button
                  type="button"
                  role="menuitem"
                  className="block w-full rounded-lg px-3 py-2 text-left text-sm text-slate-300 hover:bg-white/5 hover:text-slate-50"
                  onClick={() => {
                    setSettingsOpen(false);
                    setCatalogOpen(true);
                  }}
                >
                  Feature catalog
                </button>
                <button
                  type="button"
                  role="menuitem"
                  className="block w-full rounded-lg px-3 py-2 text-left text-sm text-slate-300 hover:bg-white/5 hover:text-slate-50"
                  onClick={() => {
                    setSettingsOpen(false);
                    setDeveloperOpen(true);
                  }}
                >
                  Developer options
                </button>
                {adminLinks.length ? (
                  <>
                    <MenuLabel>Admin</MenuLabel>
                    {adminLinks.map((link) => (
                      <SettingsItem
                        key={link.href}
                        link={withProject(link.href, projectOrigin) === link.href ? link : { ...link, href: withProject(link.href, projectOrigin) }}
                        onClick={() => setSettingsOpen(false)}
                      />
                    ))}
                  </>
                ) : null}
                <div className="my-1.5 border-t border-slate-700/80" role="separator" />
                <p
                  className="truncate px-3 py-2 text-xs text-slate-500"
                  title={userEmail}
                  role="menuitem"
                >
                  {userEmail}
                </p>
                <button
                  type="button"
                  role="menuitem"
                  disabled={signingOut}
                  onClick={() => void signOut()}
                  className="mt-0.5 w-full rounded-lg px-3 py-2 text-left text-sm font-medium text-rose-300 transition hover:bg-rose-500/15 hover:text-rose-200 disabled:opacity-60"
                >
                  {signingOut ? "Signing out…" : "Sign out"}
                </button>
              </div>
            </div>

            <button
              type="button"
              className="flex h-10 w-10 items-center justify-center rounded-full border border-slate-600/50 bg-slate-900/60 text-slate-200 transition duration-200 hover:border-emerald-500/35 hover:bg-emerald-500/10 md:hidden"
              aria-expanded={mobileOpen}
              aria-controls={mobileDrawerId}
              onClick={() => setMobileOpen((o) => !o)}
            >
              <span className="sr-only">{mobileOpen ? "Close menu" : "Open menu"}</span>
              {mobileOpen ? <CloseIcon /> : <MenuIcon />}
            </button>
          </div>
        </div>
      </header>

      <div
        className={`fixed inset-0 z-[60] md:hidden transition-opacity duration-300 ${
          mobileOpen ? "pointer-events-auto opacity-100" : "pointer-events-none opacity-0"
        }`}
        aria-hidden={!mobileOpen}
      >
        <button
          type="button"
          className="absolute inset-0 bg-slate-950/70 backdrop-blur-sm"
          aria-label="Close menu"
          onClick={() => setMobileOpen(false)}
        />
        <aside
          id={mobileDrawerId}
          className={`absolute right-0 top-0 flex h-full w-[min(100%,20rem)] flex-col border-l border-violet-500/20 bg-slate-950 shadow-2xl transition-transform duration-300 ease-out ${
            mobileOpen ? "translate-x-0" : "translate-x-full"
          }`}
          aria-label="Mobile navigation"
        >
          <div className="flex items-center justify-between border-b border-slate-800/80 px-4 py-4">
            <span className="text-sm font-semibold text-slate-100">Navigation</span>
            <button
              type="button"
              className="flex h-9 w-9 items-center justify-center rounded-full text-slate-400 hover:bg-white/5 hover:text-slate-100"
              onClick={() => setMobileOpen(false)}
            >
              <span className="sr-only">Close</span>
              <CloseIcon />
            </button>
          </div>

          <nav className="flex-1 overflow-y-auto px-3 py-4" aria-label="Navigation">
            <p className="px-3 pb-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-slate-500">
              Project
            </p>
            <ul className="mb-4 space-y-0.5">
              <li>
                <button
                  type="button"
                  className="w-full rounded-lg px-3 py-2 text-left text-sm text-slate-200 hover:bg-white/5"
                  onClick={() => {
                    selectProject("");
                    setMobileOpen(false);
                  }}
                >
                  All Projects
                </button>
              </li>
              {projects.map((project) => (
                <li key={project.project_origin}>
                  <button
                    type="button"
                    className="w-full rounded-lg px-3 py-2 text-left text-sm text-slate-200 hover:bg-white/5"
                    onClick={() => {
                      selectProject(project.project_origin);
                      setMobileOpen(false);
                    }}
                  >
                    {project.display_name?.trim() || project.project_origin}
                  </button>
                </li>
              ))}
            </ul>
            <ul className="space-y-0.5">
              {primaryLinks.map((link) => (
                <li key={link.href}>
                  <NavLinkItem
                    link={link}
                    active={isLinkActive(pathname, link)}
                    onNavigate={() => setMobileOpen(false)}
                  />
                </li>
              ))}
            </ul>

            <p className="mt-6 px-3 pb-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-violet-400/80">
              Account
            </p>
            <ul className="space-y-0.5">
              {accountLinks.map((link) => (
                <li key={link.href}>
                  <NavLinkItem
                    link={link}
                    active={isLinkActive(pathname, link)}
                    onNavigate={() => setMobileOpen(false)}
                  />
                </li>
              ))}
            </ul>
            <p className="mt-4 px-3 pb-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-violet-400/80">
              Product
            </p>
            <ul className="space-y-0.5">
              {productLinks.map((link) => (
                <li key={link.href}>
                  <NavLinkItem
                    link={link}
                    active={isLinkActive(pathname, link)}
                    onNavigate={() => setMobileOpen(false)}
                  />
                </li>
              ))}
            </ul>
            {adminLinks.length ? (
              <>
                <p className="mt-4 px-3 pb-2 text-[10px] font-semibold uppercase tracking-[0.2em] text-violet-400/80">
                  Admin
                </p>
                <ul className="space-y-0.5">
                  {adminLinks.map((link) => (
                    <li key={link.href}>
                      <NavLinkItem
                        link={link}
                        active={isLinkActive(pathname, link)}
                        onNavigate={() => setMobileOpen(false)}
                      />
                    </li>
                  ))}
                </ul>
              </>
            ) : null}
          </nav>

        </aside>
      </div>
      {catalogOpen ? (
        <FeatureCatalogDrawer onClose={() => setCatalogOpen(false)} />
      ) : null}
      {developerOpen ? (
        <DeveloperOptionsDrawer
          projectOrigin={projectOrigin}
          onClose={() => setDeveloperOpen(false)}
        />
      ) : null}
    </>
  );
}

function FeatureCatalogDrawer({ onClose }: { onClose: () => void }) {
  const [lines, setLines] = useState<string[]>([]);
  useEffect(() => {
    let cancelled = false;
    void fetch("/api/msgf/dashboard/savings-features", { credentials: "include" })
      .then((res) => res.json())
      .then((json: { catalog?: { label: string; enabled: boolean; description: string }[] }) => {
        if (cancelled || !Array.isArray(json.catalog)) return;
        setLines(
          json.catalog.map(
            (entry) => `${entry.enabled ? "On" : "Off"} · ${entry.label} — ${entry.description}`
          )
        );
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);
  return (
    <Drawer title="Feature catalog" onClose={onClose}>
      {lines.length ? (
        <ul className="space-y-2 text-sm text-slate-300">
          {lines.map((line) => (
            <li key={line}>{line}</li>
          ))}
        </ul>
      ) : (
        <p className="text-sm text-slate-400">Catalog loads when savings counters are available.</p>
      )}
    </Drawer>
  );
}

