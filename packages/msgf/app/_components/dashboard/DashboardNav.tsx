import Link from "next/link";
import { useRouter } from "next/navigation";
import { useCallback, useState } from "react";

import { BrandLogo } from "@/app/_components/brand/BrandLogo";
import { createClient } from "@/utils/supabase/client";

type Props = {
  userEmail: string;
  showAdminPortalLink?: boolean;
  tokenSavingsHref?: string;
};

export function DashboardNav({
  userEmail,
  showAdminPortalLink = false,
  tokenSavingsHref = "/dashboard#token-savings",
}: Props) {
  const router = useRouter();
  const [signingOut, setSigningOut] = useState(false);

  const signOut = useCallback(async () => {
    setSigningOut(true);
    try {
      const supabase = createClient();
      await supabase.auth.signOut();
      router.replace("/sign-in");
      router.refresh();
    } catch {
      window.location.assign("/sign-in");
    }
  }, [router]);

  return (
    <header className="sticky top-0 z-50 border-b border-violet-500/10 bg-slate-950/70 backdrop-blur-xl">
      <div className="mx-auto flex max-w-6xl flex-wrap items-center justify-between gap-3 px-5 py-4">
        <Link href="/dashboard" className="group flex items-center gap-2.5">
          <BrandLogo
            size={36}
            decorative
            className="border border-emerald-400/30 bg-emerald-500/10"
          />
          <div className="leading-tight">
            <span className="block text-sm font-semibold tracking-tight text-slate-100 group-hover:text-emerald-200">
              Elphie&apos;s Gated AI
            </span>
            <span className="block text-[11px] text-slate-500">Glass-box platform</span>
          </div>
        </Link>

        <nav className="flex flex-wrap items-center gap-2 sm:gap-3" aria-label="Dashboard">
          {showAdminPortalLink ? (
            <Link
              href="/admin/portal"
              className="rounded-full px-3 py-1.5 text-sm text-violet-400/90 transition hover:bg-violet-500/10 hover:text-violet-200"
            >
              Admin portal
            </Link>
          ) : null}
          <Link
            href="/other-products"
            className="rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200"
          >
            Other products
          </Link>
          <Link
            href="/getting-started#six-pillars"
            className="hidden rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200 md:inline"
          >
            Pillar guide
          </Link>
          <Link
            href={tokenSavingsHref}
            className="hidden rounded-full px-3 py-1.5 text-sm text-amber-400/90 transition hover:bg-amber-500/10 hover:text-amber-200 sm:inline"
          >
            Token savings
          </Link>
          <Link
            href="/workspace"
            className="rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200"
          >
            Workspace
          </Link>
          <Link
            href="/setup/projects"
            className="rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200"
          >
            Projects
          </Link>
          <Link
            href="/workspace#ide-setup"
            className="hidden rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200 sm:inline"
          >
            IDE setup
          </Link>
          <Link
            href="/status"
            className="rounded-full px-3 py-1.5 text-sm text-slate-400 transition hover:bg-white/5 hover:text-slate-200"
          >
            System status
          </Link>
          <span className="hidden max-w-[12rem] truncate text-sm text-slate-500 sm:inline" title={userEmail}>
            {userEmail}
          </span>
          <button
            type="button"
            onClick={() => void signOut()}
            disabled={signingOut}
            className="rounded-full border border-violet-500/25 bg-violet-500/10 px-4 py-2 text-sm font-medium text-violet-200 transition hover:border-violet-400/40 hover:bg-violet-500/20 disabled:opacity-60"
          >
            {signingOut ? "Signing out…" : "Sign out"}
          </button>
        </nav>
      </div>
    </header>
  );
}
