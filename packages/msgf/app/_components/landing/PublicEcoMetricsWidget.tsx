import { useEffect, useMemo, useState } from "react";

import { calculateEcoSavings, type EcoMetrics } from "@/lib/utils/ecoCalculator";
import {
  buildEcoEquivalencyStatements,
  CO2_LBS_PER_TREE_SEEDLING_10_YEARS,
  type EcoEquivalencyStatements,
} from "@/lib/utils/ecoEquivalencies";
import { formatDisplayDateTime } from "@/lib/utils/formatLocale";

type PublicEcoMetricsPayload = {
  ok: true;
  source: "live" | "empty" | "mock";
  generated_at: string;
  metrics: EcoMetrics;
  equivalencies: EcoEquivalencyStatements;
  claimable?: boolean;
  methodology?: string;
  disclaimer?: string;
};

type StatCardProps = {
  label: string;
  value: string;
  equivalent: string;
  tone: "water" | "carbon" | "energy";
};

const EMPTY_METRICS = calculateEcoSavings(0);
const FALLBACK_PAYLOAD: PublicEcoMetricsPayload = {
  ok: true,
  source: "empty",
  generated_at: new Date(0).toISOString(),
  metrics: EMPTY_METRICS,
  equivalencies: buildEcoEquivalencyStatements(EMPTY_METRICS),
  claimable: false,
  methodology:
    "Eco impact uses published coefficients applied only to proven avoided tokens.",
  disclaimer:
    "No claimable public totals until proven avoidance events are recorded.",
};

function formatMetric(value: number, unit: string): string {
  return `${value.toLocaleString(undefined, { maximumFractionDigits: 2 })} ${unit}`;
}

function formatTokenCount(value: number): string {
  if (value >= 1_000_000_000) {
    return `${(value / 1_000_000_000).toLocaleString(undefined, { maximumFractionDigits: 2 })}B`;
  }
  if (value >= 1_000_000) {
    return `${(value / 1_000_000).toLocaleString(undefined, { maximumFractionDigits: 2 })}M`;
  }
  return value.toLocaleString();
}

function formatStatementNumber(value: number, maximumFractionDigits = 1): string {
  return value.toLocaleString(undefined, {
    maximumFractionDigits,
  });
}

function toneClasses(tone: StatCardProps["tone"]): string {
  if (tone === "water") return "border-cyan-400/25 bg-cyan-500/10 text-cyan-100";
  if (tone === "carbon") return "border-emerald-400/25 bg-emerald-500/10 text-emerald-100";
  return "border-amber-400/25 bg-amber-500/10 text-amber-100";
}

function StatCard({ label, value, equivalent, tone }: StatCardProps) {
  return (
    <article className={`rounded-2xl border p-5 ${toneClasses(tone)}`}>
      <p className="text-[11px] font-semibold uppercase tracking-[0.2em] opacity-75">
        {label}
      </p>
      <p className="mt-2 text-3xl font-bold tracking-tight text-white">{value}</p>
      <p className="mt-3 text-sm leading-relaxed opacity-85">{equivalent}</p>
    </article>
  );
}

export function PublicEcoMetricsWidget() {
  const [payload, setPayload] = useState<PublicEcoMetricsPayload | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let active = true;
    async function loadMetrics() {
      try {
        const res = await fetch("/api/public-eco-metrics", {
          cache: "no-store",
        });
        if (!res.ok) {
          throw new Error(`public eco metrics returned ${res.status}`);
        }
        const json = (await res.json()) as PublicEcoMetricsPayload;
        if (active && json.ok) {
          setPayload(json);
        }
      } catch {
        if (active) {
          setPayload(FALLBACK_PAYLOAD);
        }
      } finally {
        if (active) {
          setLoading(false);
        }
      }
    }

    void loadMetrics();
    return () => {
      active = false;
    };
  }, []);

  const data = payload ?? FALLBACK_PAYLOAD;
  const generatedAt = useMemo(() => new Date(data.generated_at), [data.generated_at]);
  const treeEquivalent = data.metrics.co2e_offset_lbs / CO2_LBS_PER_TREE_SEEDLING_10_YEARS;
  const claimable = data.claimable === true && data.metrics.tokens_saved > 0;

  if (loading || data.source !== "live") {
    return null;
  }

  return (
    <section className="rounded-3xl border border-emerald-500/20 bg-slate-950/70 p-6 shadow-2xl shadow-emerald-950/20 backdrop-blur-xl sm:p-8">
      <div className="grid gap-8 lg:grid-cols-[0.85fr_1.15fr] lg:items-center">
        <div>
          <p className="text-xs font-semibold uppercase tracking-[0.28em] text-emerald-300/90">
            Network impact · marketing totals
          </p>
          <h2 className="mt-4 text-4xl font-black leading-[1.02] tracking-tight text-white sm:text-5xl">
            AI that doesn&apos;t cost the Earth
          </h2>
          <p className="mt-5 max-w-xl text-sm leading-relaxed text-slate-300 sm:text-base">
            Public network totals — not your private governance dashboard. We only publish
            environmental impact from{" "}
            <strong className="text-emerald-200">proven avoided provider tokens</strong> — metered
            consensus baselines when cost-efficient routing skips cloud calls, or audited pack deltas from
            verify / Run Scripts. Estimates never inflate this board.
          </p>
          <p className="mt-5 max-w-xl rounded-2xl border border-emerald-400/20 bg-emerald-500/10 p-4 text-sm font-medium leading-relaxed text-emerald-50">
            {claimable ? (
              <>
                Proven network diversion: {formatTokenCount(data.metrics.tokens_saved)} tokens.
                Modeled impact: {formatStatementNumber(data.metrics.grid_compute_prevented_kwh, 2)}{" "}
                kWh grid power avoided (~{formatStatementNumber(treeEquivalent, 1)} tree-seedling
                CO₂e proxy) and{" "}
                {formatStatementNumber(data.metrics.freshwater_conserved_gallons, 2)} gallons
                freshwater cooling proxy.
              </>
            ) : (
              <>
                The first number appears after an Active cache hit or a verify pack that avoided
                provider tokens. Shadow projected dollars stay off this board.{" "}
                <a href="/shadow-trial" className="underline">
                  Start in shadow mode
                </a>
                , then set enforcement mode and open proven savings.
              </>
            )}
          </p>
          <p className="mt-3 max-w-xl text-[11px] leading-relaxed text-slate-500">
            {data.methodology ?? data.disclaimer}
          </p>
          <div className="mt-5 flex flex-wrap gap-2 text-xs text-slate-400">
            <span className="rounded-full border border-emerald-500/25 bg-emerald-500/10 px-3 py-1 text-emerald-100">
              {loading
                ? "Loading live metrics"
                : claimable
                  ? "live · proven only"
                  : "empty · awaiting proven events"}
            </span>
            <span className="rounded-full border border-violet-500/20 bg-violet-500/10 px-3 py-1 text-violet-100">
              Updated {formatDisplayDateTime(generatedAt)}
            </span>
          </div>
        </div>

        <div className="grid gap-4 sm:grid-cols-3 lg:grid-cols-1 xl:grid-cols-3">
          {loading ? (
            <>
              <div className="h-40 animate-pulse rounded-2xl border border-cyan-400/15 bg-cyan-500/5" />
              <div className="h-40 animate-pulse rounded-2xl border border-emerald-400/15 bg-emerald-500/5" />
              <div className="h-40 animate-pulse rounded-2xl border border-amber-400/15 bg-amber-500/5" />
            </>
          ) : (
            <>
              <StatCard
                label="Water"
                value={formatMetric(data.metrics.freshwater_conserved_gallons, "gal")}
                equivalent={data.equivalencies.water_bottles_saved}
                tone="water"
              />
              <StatCard
                label="Carbon"
                value={formatMetric(data.metrics.co2e_offset_lbs, "lbs CO2e")}
                equivalent={data.equivalencies.tree_seedlings_equivalent}
                tone="carbon"
              />
              <StatCard
                label="Energy"
                value={formatMetric(data.metrics.grid_compute_prevented_kwh, "kWh")}
                equivalent={data.equivalencies.tesla_model_3_charges_equivalent}
                tone="energy"
              />
            </>
          )}
        </div>
      </div>
    </section>
  );
}
